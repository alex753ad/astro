"""Шаг 8.2: голос продукта в статических текстах — «ё», «AI/ИИ», род на «ты».

Источники — те же, что у широкой проверки эзотерики (`test_prompt_words._wide`:
промпты, пуши, письма, виджет, сторис, база знаний чата, лента), плюс
методичка транзитов. Эзотерику держит `test_prompt_words`, «вы» —
`test_informal_address`.

Исключения — по ТОЧНОЙ фразе, не по файлу (решение владельца 07.10.2026):
исключение на файл спрятало бы новое нарушение рядом со старым. Каждая фраза
обязана ещё встречаться — иначе она прячет уже чужой текст.

«ё» обязательна в статических текстах (решение владельца 07.10.2026); в
текстах модели не считается (`interpretation/text_check.py`). Список — только
слова, где «е» вместо «ё» ошибка без вариантов: «все», «небо», «легко»,
«звезды» сюда не входят — у них есть верное написание через «е».
"""
import re

import pytest

from backend.interpretation.gender_check import gendered_you
from backend.tests.test_prompt_words import BACKEND, _json_strings, _wide

SOURCES = list(_wide()) + list(_json_strings(BACKEND / "transit" / "methodology.json"))

NO_YO = re.compile(
    r"(?<![а-яё])(?:еще|ее|идет|придет|пойдет|найдет|ждет|живет|берет|дает|зовет|несет|ведет|"
    r"растет|поймет|начнет|пройдет|уйдет|подойдет|вперед|нашел|пришел|ушел|прошел|вошел|перешел|"
    r"твое|свое|мое|твоем|своем|моем|легкий|легкая|легкое|легкие|легкость|тяжелый|тяжелая|тяжелое|"
    r"четкий|четко|жесткий|жестко|ребенок|ребенка|прием|объем|отчет|расчет|подъем|полет|шепот|"
    r"темный|темная|темное)(?![а-яё])",
    re.I,
)

AI = re.compile(r"\b(?:ai|ии)\b", re.I)

# фраза → почему можно
AI_РАЗРЕШЕНО = {
    "Никаких слов «AI», «ИИ», «нейросеть»": "запрет в промпте прогноза (forecast/prompts.py)",
    "AI API error %s: %s": "строка лога чата, человеку не показывается",
}

# Примеры, на которых промпт объясняет правило (address.ADDRESS_RULE,
# forecast/prompts.py) — в кавычках, как в исходнике.
_RULE_EXAMPLES = (
    "«ты сам»", "«ты сделал»", "«ты рада»", "«ты спокойный»", "«видят тебя уверенной»",
    "«будь осторожен»", "«ты склонен»", "«будешь успешен»",
    "«чувствовать себя опустошённым»", "«быть настоящим»", "«делает тебя живым»",
    "«становишься мягкой»",
)
РОД_РАЗРЕШЕНО = {
    **{p: "пример в правиле промпта" for p in _RULE_EXAMPLES},
    "Этот процесс может быть интенсивным": "о процессе, не о человеке",
    "Текущая сводка (может быть пустой)": "о сводке, не о человеке",
    "наделяет тебя яркой инициативностью": "творительный существительного",
    "наделяет тебя живым умом": "творительный существительного",
    "наделяет тебя аналитическим умом": "творительный существительного",
    "наделяет тебя глубиной": "творительный существительного",
    "наделяет тебя глубокой интуицией": "творительный существительного",
    "Я окружаю себя красивым": "средний род: «красивым» — вещи вокруг",
    "не требуй от себя идеальной внешности": "родительный существительного",
}


def _strip(text: str, allowed: dict) -> str:
    for phrase in allowed:
        text = text.replace(phrase, "")
    return text


def test_scanner_sees_sources():
    assert len(SOURCES) > 1000
    assert sum(t.count("ё") for _, t in SOURCES) > 100


@pytest.mark.parametrize("allowed", [AI_РАЗРЕШЕНО, РОД_РАЗРЕШЕНО], ids=["ai", "род"])
def test_exceptions_still_used(allowed):
    unused = [p for p in allowed if not any(p in t for _, t in SOURCES)]
    assert not unused, f"исключение больше не встречается — убрать: {unused}"


def test_yo_in_static_texts():
    bad = [f"{w}: {m.group(0)}" for w, t in SOURCES for m in NO_YO.finditer(t)]
    assert not bad, "\n".join(bad)


def test_no_ai_word():
    bad = [f"{w}: {m.group(0)}" for w, t in SOURCES for m in AI.finditer(_strip(t, AI_РАЗРЕШЕНО))]
    assert not bad, "\n".join(bad)


def test_no_gendered_you():
    bad = [f"{w}: {h}" for w, t in SOURCES for h in gendered_you(_strip(t, РОД_РАЗРЕШЕНО))]
    assert not bad, "\n".join(bad)


@pytest.mark.parametrize("text,ok", [
    ("Ты еще успеешь.", False),
    ("Ты ещё успеешь.", True),
    ("Всё идет своим чередом.", False),
    ("Это легко.", True),
])
def test_no_yo_pattern(text, ok):
    assert (NO_YO.search(text) is None) is ok
