"""Исключение предохранителя сети — отдельным модулем, а не в conftest.py.

Почему не в conftest. pytest импортирует conftest.py под своим именем модуля
(здесь — `ASTRO.backend.tests.conftest`, оно зависит от rootdir и наличия
__init__.py), а тест, написавший `from backend.tests.conftest import ...`,
загружает ВТОРУЮ копию того же файла под другим именем. Классы в этих двух
копиях — разные объекты, и `pytest.raises(OutboundNetworkBlocked)` не ловит
исключение, поднятое фикстурой: тест падает с непойманным исключением,
которое на экране выглядит буквально тем же самым, что он и ждёт.

Отдельный обычный модуль импортируется одинаково с обеих сторон.
"""


class OutboundNetworkBlocked(RuntimeError):
    """Тест попытался обратиться к внешнему сервису."""
