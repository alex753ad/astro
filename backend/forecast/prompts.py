def _day_meanings(f: DayFacts) -> str:
    lines = []
    if f.houses:
        for h in f.houses:
            focus, actions = HOUSE_FOCUS[h]
            lines.append(f"- Фокус дня: {focus} (подходит: {actions}).")
    else:
        lines.append(f"- Общий тон дня: {MOON_SIGN_MOOD.get(f.moon_sign, 'ровный день')}.")
    for a in f.aspects:
        sphere = NATAL_SPHERE.get(a["natal"])
        if sphere:
            lines.append(f"- {TONE_RU[a['tone']].capitalize()} акцент на теме: {sphere}.")
    if not f.aspects:
        lines.append("- Острых акцентов нет: день ровный, держись своего ритма.")
    return "\n".join(lines)


def first_sentence(text: str) -> str:
    """Первая фраза текста — то, что человек читает первым."""
    t = (text or "").strip()
    return re.split(r"(?<=[.!?…])\s+", t, maxsplit=1)[0] if t else ""


def _previous_rule(openings: list[str]) -> str:
    """Начала прошлых дней с просьбой начать иначе.

    Зачем (замер 24.09.2026, 30 дней служебной карты): каждый день пишется
    с нуля, и модель находит одну формулу начала и держится её. Запрет
    конкретной формулы не помогает — её место занимает следующая: без
    подсказки «в этот день» 24 из 30 начинались с «Главное…», без «главного» —
    22 из 30 с «День складывается вокруг…». Лечит только знание того, как
    начинались соседние дни. Отбраковки по сходству нет — решение владельца.
    """
    if not openings:
        return ""
    lines = "\n".join(f"  — «{o}»" for o in openings)
    return ("- Так начинались прогнозы прошлых дней. Начни по-другому: "
            "не повторяй ни их первых слов, ни построения первой фразы.\n" + lines + "\n")


