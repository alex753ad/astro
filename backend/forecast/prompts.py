def lunation_allowed(f: LunationFacts) -> tuple[set[str], set[str]]:
    """Даты и время, которые код считает и разрешает модели упоминать."""
    dates = {date_ru(f.at_local.date())} | {date_ru(w["date"]) for w in f.warnings}
    times = {f.at_local.strftime("%H:%M"), f"{f.at_local.hour}:{f.at_local.minute:02d}"}
    return dates, times


def _lunation_meanings(f: LunationFacts) -> str:
    phase = PHASE_RU[f.phase]
    lines = [
        f"- Событие: {phase} в знаке {f.sign} — {date_ru(f.at_local.date())}, {f.at_local.strftime('%H:%M')} по времени читателя.",
        f"- Что значит знак {f.sign} простыми словами: {SIGN_MEANING.get(f.sign, '')}.",
    ]
    if f.house:
        focus, actions = HOUSE_FOCUS[f.house]
        lines.append(f"- Главная сфера этой фазы у человека: {focus} (подходит: {actions}).")
    for a in f.aspects:
        sphere = NATAL_SPHERE.get(a["natal"])
        if sphere:
            lines.append(
                f"- {PLANET_RU.get(a['planet'], a['planet'])}: {TONE_RU[a['tone']]} акцент на теме «{sphere}»."
            )
    for w in f.warnings:
        sphere = NATAL_SPHERE.get(w["natal"])
        if sphere:
            lines.append(
                f"- {date_ru(w['date'])} — напряжённый день ({PLANET_RU.get(w['planet'], w['planet'])}), тема «{sphere}»."
            )
    return "\n".join(lines)


def build_lunation_prompt(f: LunationFacts) -> str:
    need_warning = lunation_needs_warning(f)
    dates, times = lunation_allowed(f)
    warning_rule = (
        "Есть напряжённые акценты — блок warning ОБЯЗАТЕЛЕН: text (1–2 предложения, что может мешать) и tips (3–5 практичных советов, что делать или чего не делать)."
        if need_warning else
        "Напряжённых акцентов нет — warning: null."
    )
    return f"""Ты пишешь личный прогноз на {PHASE_RU[f.phase]} для приложения — по карте конкретного человека, а не общий пост.

Факты, посчитанные по карте:
{_lunation_meanings(f)}

Форма ответа — строго JSON, без текста вокруг:
{{
  "headline": "суть дня одной фразой: «Сегодня … а значит …»",
  "sign_meaning": "1–2 предложения: что значит знак фазы простыми словами",
  "actions": ["5–7 коротких конкретных действий"],
  "warning": {{"text": "...", "tips": ["..."]}} или null,
  "closing": "1–2 ободряющих предложения с образом"
}}

Правила:
- {warning_rule}
- Знак фазы и планеты называть можно, но СРАЗУ с пояснением: «Марс рядом, а значит сил хватит на старт».
- О характере влияния — только «гармоничный» или «напряжённый».
- Даты — только эти: {", ".join(sorted(dates))}. Время — только {", ".join(sorted(times))}. Других дат и времени не пиши.
- Без эмодзи и маркеров списка внутри строк: их поставит приложение.
{_RULES_COMMON}

Два образца тона и формы. Они общие и в вежливой форме — твой текст личный и на «ты». Их содержание (Меркурий, Дева, Стрелец, конкретные даты и советы) НЕ повторяй:
--- образец 1 ---
{LUNATION_SAMPLE_1}
--- образец 2 ---
{LUNATION_SAMPLE_2}
---"""


def lunation_needs_warning(f: LunationFacts) -> bool:
    return bool(f.warnings) or any(a["tone"] == "tense" for a in f.aspects)
