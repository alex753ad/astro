def daily_fallback(f: DayFacts) -> list[str]:
    n = f.local_date.toordinal()
    if f.houses:
        focus, actions = HOUSE_FOCUS[f.houses[0]]
        first = pick(_HOUSE_OPENING, n).format(focus=focus, actions=actions)
    else:
        mood = MOON_SIGN_MOOD.get(f.moon_sign, "всё идёт ровно, без резких поворотов")
        first = pick(_MOOD_OPENING, n).format(mood=mood)

    middle = []
    for i, a in enumerate(f.aspects[:2]):
        sphere = NATAL_SPHERE.get(a["natal"])
        if sphere:
            middle.append(pick(TONE_PHRASE[a["tone"]], n, 1 + i).format(sphere=sphere))
    second = " ".join(middle) if middle else pick(_CALM, n, 1)
    return [first, second, pick(_EVENING, n, 2)]


# Номер лунного цикла: у двух новолуний (полнолуний) подряд он соседний, как
# номер дня у соседних дней. Порядковый номер дня здесь не годится: между
# фазами 29–30 суток, и при 30 остаток от деления на 3 совпал бы.
_SYNODIC_DAYS = 29.530588853


def _cycle(f: LunationFacts) -> int:
    return round(f.at_utc.timestamp() / 86400 / _SYNODIC_DAYS)


def lunation_fallback(f: LunationFacts) -> dict:
    phase = PHASE_RU[f.phase]
    is_new = f.phase == "new_moon"
    tense = [a for a in f.aspects if a["tone"] == "tense"]
    n = _cycle(f)
    ease = "легко" if not tense else "с усилием, но уверенно"
    if is_new:
        headlines = [
            f"Сегодня {phase}, а значит начинается новый цикл — и идёт он {ease}.",
            f"Сегодня {phase}, а значит пора задумать новое — "
            f"{'легко и без сопротивления' if not tense else 'пусть и с усилием'}.",
            f"Сегодня {phase}, а значит самое время для первого шага"
            f"{'' if not tense else ' — хоть и не без напряжения'}.",
        ]
        closings = [
            "То, что посажено сейчас, прорастёт не сразу — просто продолжай поливать.",
            "Новое начинается тихо — достаточно одного честного шага, остальное приложится.",
            "Не торопи результат: сейчас важнее направление, чем скорость.",
        ]
    else:
        headlines = [
            f"Сегодня {phase}, а значит подходит к итогу то, что зрело последние недели, — "
            f"и идёт это {ease}.",
            f"Сегодня {phase}, а значит пора подвести черту под последними неделями — "
            f"{'спокойно и ясно' if not tense else 'пусть и с усилием'}.",
            f"Сегодня {phase}, а значит хорошо видно, что получилось, а что нет"
            f"{'' if not tense else ' — хоть и не без напряжения'}.",
        ]
        closings = [
            "Полная Луна освещает всё до конца — пусть этот свет покажет, что стоит сохранить.",
            "Что завершилось — пусть завершится: освободившееся место скоро займёт новое.",
            "Итоги — не приговор, а подсказка: сохрани то, что работает, и спокойно отпусти остальное.",
        ]
    headline = pick(headlines, n)
    sign_meaning = f"Знак этой фазы — {f.sign}, а значит в центре внимания {SIGN_MEANING.get(f.sign, 'твои личные дела')}."
    if is_new:
        actions = [
            "Запиши одно главное желание на этот месяц — коротко и конкретно.",
            "Выбери одну область для перемен и не пытайся менять всё сразу.",
            "Составь простой план на ближайшие недели.",
            "Начни то, что давно откладывалось, хотя бы с первого маленького шага.",
            SIGN_ACTION.get(f.sign, "Сделай сегодня что-то приятное для себя."),
        ]
    else:
        actions = [
            "Подведи итог последних недель: что получилось, что нет.",
            "Заверши одно дело, которое давно висит.",
            "Отпусти то, что больше не работает, — привычку, обиду, лишнее обязательство.",
            "Поблагодари тех, кто помог тебе в этом месяце.",
            SIGN_ACTION.get(f.sign, "Сделай сегодня что-то приятное для себя."),
        ]
    if f.house:
        focus, _ = HOUSE_FOCUS[f.house]
        actions.append(f"Удели особое внимание теме «{focus}» — сейчас она откликается сильнее всего.")

    warning = None
    if tense or f.warnings:
        when = f" Особенно {date_ru(f.warnings[0]['date'])}." if f.warnings else ""
        warning = {
            "text": "Возможны напряжение и спешка: легко сорваться или решить сгоряча." + when,
            "tips": [
                "Важные договорённости фиксируй письменно.",
                "Не принимай серьёзных решений на эмоциях — дай себе ночь.",
                "Дели большие задачи на маленькие шаги.",
            ],
        }
    return {
        "headline": headline, "sign_meaning": sign_meaning, "actions": actions,
        "warning": warning, "closing": pick(closings, n, 1),
    }
