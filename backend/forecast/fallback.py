"""Запасной текст — когда модель недоступна, бюджет исчерпан или ответ не
прошёл проверку. Собирается из тех же смыслов, что уходят в промпт, и обязан
проходить ту же проверку (закреплено тестом): «не 503» не должно значить
«текст с терминами».

Каждая фраза — в трёх вариантах, выбор по номеру дня (`pick`). До 24.09.2026
вариант был один: на одних и тех же смыслах (Луна в том же доме, то же
касание медленной планеты) запасной текст повторялся день в день, а третий
абзац не менялся никогда.

⚠️ Выбор детерминированный, не случайный: повторное открытие в тот же день
обязано дать тот же текст — запасной не кэшируется, и случайный выбор менял бы
прогноз на каждом открытии. Номер дня берётся ПОЛНЫЙ (`toordinal`), а не день
месяца: у 31-го и 1-го числа остатки от деления на 3 совпадают, у соседних
порядковых номеров — никогда.
"""
from __future__ import annotations

from backend.forecast.facts import DayFacts, LunationFacts
from backend.forecast.meanings import (
    HOUSE_FOCUS, MOON_SIGN_MOOD, NATAL_SPHERE, PHASE_RU, SIGN_ACTION, SIGN_MEANING, TONE_PHRASE,
)
from backend.forecast.validate import date_ru


def pick(variants: list, n: int, slot: int = 0):
    """Вариант номер `n + slot` по кругу. У соседних n выбор всегда разный,
    если вариантов больше одного; `slot` разводит абзацы между собой."""
    return variants[(n + slot) % len(variants)]


