"""Детектор родовых форм в обращении на «ты» — только лог и счётчик.

Пола человека мы не знаем (CLAUDE.md, «„Ты“ не должно угадывать пол»), а
модель всё равно пишет «видят тебя уверенной», «ты спокойный наблюдатель».
Правило стоит в промпте (`address.ADDRESS_RULE`), но промпт — просьба, а не
гарантия. Решение владельца 28.09.2026: ответ не отбраковывать и не
переписывать, а считать — строка в логе и число в сводке самопроверки
(`selfcheck.stats_line`), без сигнала тревоги.

Поиск намеренно узкий: только конструкции, где род прилагательного или
глагола привязан к «ты/тебя». Ложные срабатывания допустимы (это счётчик, не
фильтр), но каждое правило проверено на примерах в test_gender_check.py —
и на тех, что должны пройти молча.
"""

from __future__ import annotations

import logging
import re

logger = logging.getLogger("astro.gender_check")

_W = r"[а-яё]+"
# Границы слова явно: \b в сочетании с дефисом и кириллицей ведёт себя
# неочевидно, а «по-настоящему» должно оставаться одним словом.
_B = r"(?<![а-яё-])"
_E = r"(?![а-яё-])"

# Краткие прилагательные и причастия, у которых род виден по окончанию.
_SHORT = (
    r"(?:уверен|уверена|готов|готова|рад|рада|сам|сама|должен|должна|один|одна|"
    r"прав|права|свободен|свободна|спокоен|спокойна|счастлив|счастлива|нужен|нужна|"
    r"способен|способна|склонен|склонна|открыт|открыта|закрыт|закрыта|силён|сильна|"
    r"устал|устала|влюблён|влюблена|осторожен|осторожна|одинок|одинока|знаком|знакома|"
    # Из PDF 29.09.2026: «ты склонен», «будешь успешен», «можешь быть полезен».
    r"успешен|успешна|полезен|полезна|чувствителен|чувствительна)"
)
# Наречия и частицы, которые могут стоять между «ты» и словом с родом.
_ADV = r"(?:скорее|очень|довольно|вполне|не|тоже|уже|всегда|часто|так|такой|такая|по-настоящему)"
# Глаголы-связки: «ты кажешься спокойной», «ты бываешь резким».
_LINK = r"(?:бываешь|кажешься|становишься|выглядишь|остаёшься|остаешься|станешь|будешь)"

_PATTERNS = (
    # «ты сделал», «ты уже решила» — прошедшее время. Гласная перед -л:
    # «тепла», «числа» — не глаголы и не ловятся.
    re.compile(rf"{_B}ты\s+(?:{_ADV}\s+)?{_W}[аеиоуыяё](?:л|ла|лся|лась){_E}", re.I),
    # «ты уверен(а)», «ты не готова», «будь осторожен», «можешь быть
    # полезен», «ты бываешь чувствителен» — краткая форма и после связки.
    re.compile(rf"{_B}(?:ты|будь|быть|{_LINK})\s+(?:{_ADV}\s+)?(?:{_LINK}\s+)?(?:{_ADV}\s+)?{_SHORT}{_E}", re.I),
    # «ты спокойный наблюдатель», «ты — сильная»: полное прилагательное сразу
    # за «ты» (через наречие). Объект глагола («ты чувствуешь внутренний
    # покой») не попадает: между ними глагол, а не наречие.
    re.compile(rf"{_B}ты\s+(?:—\s+)?(?:{_ADV}\s+)?{_W}(?:ый|ий|ая|яя){_E}", re.I),
    # «ты кажешься спокойной», «ты бываешь резким».
    re.compile(rf"{_B}ты\s+(?:{_ADV}\s+)?{_LINK}\s+(?:{_ADV}\s+)?{_W}(?:ой|ей|ым|им){_E}", re.I),
    # «чувствовать себя опустошённым», «ощущаешь себя лишней» (из PDF
    # 29.09.2026): возвратное «себя» с творительным прилагательным.
    re.compile(rf"{_B}себя\s+(?:{_ADV}\s+)?{_W}(?:ым|им|ой|ей){_E}", re.I),
    # «видят тебя уверенной», «считают тебя сильным» — творительный после
    # «тебя». «У тебя большой…», «для тебя важной…» — родительный, не ловим.
    re.compile(rf"(?<!у )(?<!для )(?<!от )(?<!без )(?<!до )(?<!кроме ){_B}"
               rf"тебя\s+(?:{_ADV}\s+)?{_W}(?:ой|ей|ым|им){_E}", re.I),
)

# Слова, которые подходят под окончания, но рода не несут.
_SAFE_WORDS = {
    "другой", "такой", "какой", "любой", "каждый", "всякий", "иной",
    "собой", "мной", "им", "ним", "одним", "другим", "всем", "ей",
}


def gendered_you(text: str) -> list[str]:
    """Найденные родовые обороты при обращении на «ты» (пусто — чисто)."""
    hits: list[str] = []
    for rx in _PATTERNS:
        for m in rx.finditer(text or ""):
            frag = m.group(0)
            if frag.split()[-1].lower() in _SAFE_WORDS:
                continue
            hits.append(frag)
    return hits


def report(text: str, contour: str) -> int:
    """Посчитать и записать. Возвращает число находок; не бросает никогда —
    детектор не должен ронять выдачу текста человеку."""
    try:
        hits = gendered_you(text)
        if hits:
            logger.warning("gendered_you contour=%s n=%d hits=%s", contour, len(hits), hits[:5])
            from backend.forecast import stats
            stats.incr("gendered_you")
        return len(hits)
    except Exception as e:  # pragma: no cover — страховка
        logger.warning("gendered_you: проверка не выполнена: %s", e)
        return 0
