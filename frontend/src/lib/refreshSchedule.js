/**
 * refreshSchedule.js — КОГДА обновлять сессию. Чистые функции, без React.
 *
 * Вынесено из useAuth.jsx не ради красоты: в проекте нет DOM-окружения для
 * тестов (ни jsdom, ни testing-library), поэтому логику внутри хука проверить
 * нечем. А проверять здесь есть что — оба дефекта ниже нашлись именно тем,
 * что расписание было размазано по обработчикам и его никто не читал целиком.
 *
 * Дефект 1 (07.09.2026): цепочка таймера была ОДНОРАЗОВОЙ. Следующий таймер
 * ставило только успешное обновление, а `doRefresh` результат не читал вовсе.
 * Значит первый же неуспех — обрыв связи на секунду, 429 от лимитера,
 * заснувший на минуту webview — выключал автоматическое обновление до
 * перезапуска приложения, молча. Отсюда `retryDelay`.
 *
 * Дефект 2: при `delay <= 0` (токен уже протух или истекает раньше буфера)
 * таймер не ставился ВООБЩЕ и об этом никто не узнавал — вместо «обновить
 * немедленно» получалось «не делать ничего никогда». Отсюда `kind: 'now'`.
 */

import { tokenExpiresAt } from './jwt';
import { serverNow } from './serverClock';

/** За сколько до истечения обновляемся заранее. */
export const REFRESH_BUFFER_MS = 2 * 60 * 1000;

/**
 * Пол задержки. Страхует от плотного цикла, если сервер когда-нибудь начнёт
 * выдавать токены короче буфера: без пола `delay` был бы отрицательным, мы
 * обновлялись бы немедленно, получали такой же короткий токен и обновлялись
 * снова — запрос за запросом, без паузы.
 */
export const MIN_DELAY_MS = 5 * 1000;

export const RETRY_BASE_MS = 30 * 1000;
export const RETRY_MAX_MS = 5 * 60 * 1000;

/**
 * Когда обновлять токен.
 *
 *   { kind: 'now' }            — срок вышел, обновляться сейчас;
 *   { kind: 'later', delay }   — поставить таймер;
 *   { kind: 'never' }          — срок прочитать не удалось.
 *
 * 'never' — это НЕ «всё хорошо». Это отказ гадать: подпись на клиенте
 * проверить нечем, и незнакомый формат токена не должен превращаться в
 * бесконечное обновление. Такой токен уедет на сервер как есть, и решение
 * примет он — ответом 401, на который клиент обновится обычным путём.
 */
export function nextRefresh(token, now = serverNow()) {
  const expiresAt = tokenExpiresAt(token);
  if (!expiresAt) return { kind: 'never' };
  if (now >= expiresAt) return { kind: 'now' };
  return { kind: 'later', delay: Math.max(expiresAt - now - REFRESH_BUFFER_MS, MIN_DELAY_MS) };
}

/**
 * Пауза перед повтором после неудачи: 30 с, минута, две… и не больше пяти
 * минут. Удвоение, а не постоянный интервал: сервер может лежать часами, и
 * долбить его раз в полминуты всё это время незачем. Потолок, а не отказ
 * после N попыток: refresh живёт неделю, и пока он жив, у приложения есть
 * шанс восстановиться само — сдаваться раньше значит требовать вход руками
 * там, где хватило бы терпения.
 */
export function retryDelay(attempt) {
  return Math.min(RETRY_BASE_MS * 2 ** attempt, RETRY_MAX_MS);
}
