/**
 * sessionUser.js — что из ответа сервера с токенами обновляет пользователя.
 *
 * Вынесено чистой функцией по той же причине, что `lib/refreshSchedule.js` и
 * `mobile/lib/interpretRules.js`: DOM-окружения для тестов в проекте нет,
 * внутри хука проверить нечего, а ошибиться здесь легко и незаметно.
 *
 * ⚠️ Ради чего это существует. `refreshSession` (`api/client.js`) писал только
 * токены и `astro_user` не трогал, а его уведомление `onTokensRefreshed` не
 * имело НИ ОДНОГО подписчика. Ответ `/auth/refresh` при этом содержит `tier`
 * (`_build_token_response`, `backend/auth/router.py`) — поле просто
 * выбрасывалось. Следствие: смена тарифа на сервере становилась видна
 * приложению только после повторного ВХОДА, потому что `user.tier`
 * перезаписывался единственным местом — `applyTokenResponse`.
 *
 * Это и есть настоящий механизм известного симптома «оплаченный тариф не
 * применяется до перезапуска приложения». Раньше его списали на зависание
 * объекта плагина Capacitor (`Preferences` как thenable) — то зависание было
 * настоящим и починено, но симптом объясняло не оно: обновление сессии на
 * устройстве идёт через `refreshSession`, мимо `applyTokenResponse`.
 *
 * ⚠️ Сетевых запросов здесь нет и быть не должно. Тариф уже приехал в ответе
 * обновления — сходить за ним ещё раз значило бы удлинить залп на холодном
 * старте, ровно тот, из-за которого писались гейт по сроку токена и пауза
 * после неудачного обновления (CLAUDE.md, «Холодный старт упирается в
 * ЗАДЕРЖИВАЮЩИЙ лимит»).
 */

/**
 * Поля пользователя, приезжающие вместе с токенами.
 *
 * Ключ — имя в объекте `user`, значение — имя в ответе сервера. Список
 * повторяет `applyTokenResponse` (`hooks/useAuth.jsx`) и обязан с ним
 * совпадать: разойдутся — вход и обновление начнут класть в `user` разное,
 * и человек увидит одно после логина и другое через четверть часа.
 */
const FIELDS = {
  id: 'user_id',
  email: 'email',
  name: 'name',
  tier: 'tier',
  is_admin: 'is_admin',
  is_partner: 'is_partner',
};

/**
 * Обновляет пользователя данными из ответа с токенами.
 *
 * @param {object|null} prev — текущий `user` (null, если не вошли)
 * @param {object|null} data — тело ответа `/auth/refresh` или `/auth/login`
 * @returns {object|null} новый объект, если что-то изменилось; ИМЕННО `prev`,
 *          если нет — вызывающая сторона сравнивает по ссылке и не
 *          перерисовывает дерево на каждом обновлении токена.
 *
 * ⚠️ Не вошли — не «создаём» пользователя из ответа. Обновление токенов может
 * прийти в момент, когда сессия уже погашена (разлогин, отказ), и собрать из
 * него нового вошедшего значило бы воскресить того, кого только что выкинули.
 *
 * ⚠️ Отсутствующее в ответе поле НЕ затирает известное. Ответы разных ручек
 * различаются составом, и `undefined` из одной не должен стирать имя,
 * пришедшее из другой. Именно поэтому здесь перебор полей, а не spread.
 */
export function mergeUserFromTokens(prev, data) {
  if (!prev || !data) return prev;

  let changed = false;
  const next = { ...prev };
  for (const [key, field] of Object.entries(FIELDS)) {
    const value = data[field];
    if (value === undefined || value === null) continue;
    if (next[key] !== value) {
      next[key] = value;
      changed = true;
    }
  }
  return changed ? next : prev;
}
