/**
 * interpretationUpsell.js — приписка под готовым разбором: кому что предлагаем.
 *
 * Общий файл для веба и мобильного клиента, по образцу `lib/sectionStream.js`
 * и `mobile/lib/ruDeclension.js`. Заведён 09.09.2026, когда у формулировок
 * появился второй потребитель — экран разбора в приложении.
 *
 * ⚠️ Копию текстов в mobile/ не заводить. В этом проекте второй словарь
 * заголовков секций (`SECTION_TITLES_RU`) уже существовал и был удалён:
 * формулировки разошлись, и один и тот же человек видел разное на разных
 * путях. Здесь риск тот же — это продающий текст, его правят чаще прочего.
 *
 * Отдаётся не разметка, а данные: веб рисует `<Link>` роутера, приложение —
 * кнопку с `openInBrowser` (роутера у него нет, а веб-оплата из приложения
 * разрешена — RuStore). Общей может быть только копирайтинг и правило «кому
 * показывать», разметка у клиентов своя.
 */

import { TIER_NAMES } from '../constants';

/**
 * Объём разбора на Лире, вынесенный в текст кнопки.
 *
 * ⚠️ Это ВТОРОЙ источник числа: на бэкенде оно живёт в
 * `TIER_FLAGS["pro"]["interpretation_word_limit"]` (`auth/rate_limits.py`).
 * Дубль не заведён этой правкой — он был зашит прямо в кнопку
 * (`Interpretation.jsx`, «НА 2500 СЛОВ») и здесь лишь собран в одно место,
 * чтобы у мобильного клиента не появилась третья копия. Расходиться числу
 * по-прежнему есть с чем: сводить их в один источник — отдельная работа,
 * тестом эта пара сегодня не связана.
 */
export const PRO_WORDS = 2500;

/**
 * Что показать под готовым разбором.
 *
 * @param {string|undefined} tier
 * @returns {null | {kind: 'free', text: string, cta: string}
 *                | {kind: 'lite', title: string, subtitle: string, cta: string}}
 *
 * ⚠️ Pro и premium получают `null` намеренно: предлагать более глубокий разбор
 * тому, у кого он самый глубокий, — способ выглядеть навязчивым и глупым
 * разом. Ветки для них здесь нет и заводить её не надо.
 *
 * Отсутствующий тариф считается free — так же, как в вебе (`isFree = userTier
 * === 'free' || !userTier`): пока тариф не приехал, показывать предложение
 * купить безопаснее, чем показывать пустоту тому, кто уже заплатил.
 */
export function interpretationUpsell(tier) {
  if (tier === 'lite') {
    return {
      kind: 'lite',
      title: 'Получить расширенную интерпретацию',
      subtitle: `Открывается на тарифе ${TIER_NAMES.pro}`,
      cta: `НА ${PRO_WORDS} СЛОВ`,
    };
  }
  if (!tier || tier === 'free') {
    return {
      kind: 'free',
      text: `Хотите разбор подробнее? На тарифе ${TIER_NAMES.pro} интерпретация глубже и подробнее.`,
      cta: 'Тарифы →',
    };
  }
  return null;
}
