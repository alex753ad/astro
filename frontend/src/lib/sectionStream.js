/**
 * sectionStream.js — однопроходный разбор разметки `<section>` в потоке
 * интерпретации. Общий файл для веба и мобильного клиента.
 *
 * Заведён 07.09.2026 взамен `flushBuffer` из `api/client.js`, который
 * разбирал буфер ДВУМЯ проходами (сперва все открывающие теги, затем все
 * закрывающие) и потому в принципе не мог сохранить порядок между тегами и
 * текстом. Разбор потока интерпретации — задача с состоянием: тег приезжает
 * разрезанным на произвольное число событий, и решение «это текст или начало
 * тега» нельзя принять в пределах одного события. Полная разведка — в
 * INTERPRET_SSE_RECON.md.
 *
 * ⚠️ У ручки `/chart/{id}/interpret` ТРИ пути отдачи, и они ломают наивный
 * парсер по-разному — поэтому проверять его на одном живом потоке
 * бесполезно (INTERPRET_SSE_RECON.md §2):
 *
 *   1. живая генерация — теги разрезаны по токенам: `<section`, ` name`,
 *      `="`, `general`, `">\n` (боевой замер, CHART_API_RECON.md:366-377);
 *   2. Redis-кэш (`replay_as_stream`) — каждый тег отдельной порцией, текст
 *      по 8 слов; проходит через любой разумный парсер;
 *   3. сохранённый разбор из БД — ВЕСЬ документ одним событием, все 12
 *      тегов внутри него.
 *
 * Чем именно был плох прежний `flushBuffer` — двумя независимыми дефектами:
 *
 * **а) Порог удержания хвоста в 19 символов.** Незакрытый хвост придерживался
 * только пока был короче 20 символов (`lastOpen > result.length - 20`). А
 * открывающий тег длиннее: `<section name="general">` — 24 символа,
 * `<section name="relationships">` — 30. На живом пути буфер проходил через
 * состояние `<section name="general` (23 символа), удержание не срабатывало,
 * и незакрытый тег уходил наружу как обычный текст: `section_start` не
 * приходил НИ РАЗУ. Закрывающий `</section>` (10 символов) в порог
 * укладывался — отсюда асимметрия «0 открывающих против 6 закрывающих».
 * Мелкие чанки были не спасением, а ровно тем случаем, где эвристика не
 * работает. Поэтому здесь удержание **без порога длины**: хвост держится,
 * пока он ещё может стать тегом (`couldBeTagPrefix`), и освобождается в тот
 * момент, когда перестал им быть, — а не когда стал длинным.
 *
 * **б) Два прохода replace.** На пути 3 (весь документ одним событием) шесть
 * `section_start` уходили подряд ДО всякого текста: оглавление пустое, весь
 * разбор приклеивался к последней секции. Здесь — один проход слева направо,
 * события отдаются в порядке встречи в буфере.
 *
 * Инвариант, ради которого всё это: **одинаковое поведение при любой
 * нарезке**. Один и тот же документ, поданный по одному символу и одним
 * куском в 40 КБ, обязан дать побайтово одинаковую последовательность
 * событий. Это свойство проверяется тестом, а не подразумевается.
 */

/**
 * Грамматика тега — та же, что режет теги на сервере
 * (`backend/interpretation/router.py:33`, `_SECTION_TAG_RE`):
 * `</?section(?: name="[^"]+")?>\n?`.
 *
 * Отличия от серверной записи только технические: экранирован `/` (в
 * JS-литерале обязателен), добавлены две группы захвата (косая черта и имя)
 * и флаг `y` — липкое совпадение проверяется ИМЕННО в позиции найденного
 * `<`, а не где-то дальше по буферу. Язык, который принимает регулярка, тот
 * же; при правке серверной править и эту.
 *
 * ⚠️ Хвостовой `\n?` — не украшение: сервер съедает ОДИН перевод строки
 * после тега. Не съесть его здесь значит получить лишнюю пустую строку в
 * начале каждой секции на путях 2 и 3.
 */
const TAG_AT = /<(\/)?section(?: name="([^"]+)")?>\n?/y;

/** Имена секций, которые может прислать модель (`interpretation/prompts.py`,
 * строка «Допустимые имена секций»). Список нужен потребителю для заголовков
 * и порядка; парсер им НЕ фильтрует — имя вне списка отдаётся как есть (см.
 * §4 п. 9 разведки: модель может прислать что угодно, и терять такую секцию
 * нельзя). */
export const SECTION_NAMES = [
  'general', 'career', 'relationships', 'health', 'finance', 'spirituality',
];

/** Та же грамматика для построчной чистки: без хвостового `\n?` (при разборе
 * по строкам перевод уже съеден разбиением) и с флагом `g` — тегов в строке
 * может оказаться несколько. */
const TAG_GLOBAL = /<\/?section(?: name="[^"]+")?>/g;

/**
 * Снимает разметку секций со строки текста.
 *
 * Подстраховка для построчного рендера (`Interpretation.jsx`,
 * `renderMarkdown`). После перехода на `createSectionParser` теги до рендера
 * доезжать не должны — парсер снимает их из потока. Но если разметка всё же
 * просочится (текст, сохранённый в БД до 07.09.2026, ошибка модели), она
 * обязана быть УБРАНА, а не показана человеку как проза.
 *
 * Снимает теги, а не выбрасывает строку целиком: тег может стоять посреди
 * прозы, и выбрасывание унесло бы вместе с ним живой текст. Вызывающая
 * сторона отличает «строка была только тегом» по тому, что результат стал
 * пустым, — такую строку не рисуют вовсе, иначе на её месте останется
 * пустой абзац.
 *
 * Живёт здесь, а не в компоненте, чтобы грамматика тега осталась в одном
 * файле — том же, что разбирает поток.
 */
export function stripSectionTags(line) {
  return line.replace(TAG_GLOBAL, '');
}

/**
 * Может ли `s` (начинается с `<`) ещё дорасти до тега?
 *
 * Это замена порогу длины из старого `flushBuffer`. Проверка идёт по той же
 * грамматике, что и `TAG_AT`, но посимвольно и с одним вопросом: «кончился
 * ввод посреди разрешённого места?». Кончился — держим хвост дальше, сколько
 * бы символов в нём ни было. Встретили символ, которого в этой позиции быть
 * не может, — это не тег и никогда им не станет, отпускаем.
 *
 * Полный тег сюда не попадает: его раньше поймает `TAG_AT`.
 */
function couldBeTagPrefix(s) {
  let i = 1;                                    // s[0] === '<'
  if (i === s.length) return true;              // "<"
  if (s[i] === '/') {
    i++;
    if (i === s.length) return true;            // "</"
  }

  const WORD = 'section';
  let w = 0;
  while (i < s.length && w < WORD.length && s[i] === WORD[w]) { i++; w++; }
  if (w < WORD.length) return i === s.length;   // ввод кончился посреди слова
  if (i === s.length) return true;              // ровно "<section"

  // После имени тега допустимы только '>' (его поймал бы TAG_AT) и пробел
  // перед атрибутом.
  if (s[i] !== ' ') return false;
  i++;
  if (i === s.length) return true;              // "<section "

  const ATTR = 'name="';
  let a = 0;
  while (i < s.length && a < ATTR.length && s[i] === ATTR[a]) { i++; a++; }
  if (a < ATTR.length) return i === s.length;   // ввод кончился посреди name="
  if (i === s.length) return true;              // значение ещё не начиналось

  const valueStart = i;
  while (i < s.length && s[i] !== '"') i++;
  if (i === s.length) return true;              // значение ещё набирается
  if (i === valueStart) return false;           // [^"]+ требует хотя бы один символ
  i++;                                          // закрывающая кавычка
  return i === s.length;                        // ждём '>' — всё прочее не тег
}

/**
 * Создаёт разборщик одного потока.
 *
 * Состояние (недоразобранный хвост и открытая секция) живёт МЕЖДУ вызовами —
 * тег может быть разрезан на любое число событий. Поэтому на каждое
 * соединение нужен свой экземпляр: переиспользовать разборщик после
 * реконнекта нельзя, докачки у ручки нет и поток начинается сначала
 * (INTERPRET_SSE_RECON.md §1).
 *
 * `push(chunk)` и `end()` возвращают массив событий в порядке встречи:
 *   { type: 'section_start', name }
 *   { type: 'text', text }
 *   { type: 'section_end' }
 *
 * Форма событий совпадает с той, что раньше отдавал `flushBuffer`, — чтобы
 * потребители (`Interpretation.jsx`) не переписывались вслед за парсером.
 */
export function createSectionParser() {
  let buf = '';           // недоразобранный хвост между событиями
  let openSection = null; // имя открытой секции или null

  /**
   * Один проход слева направо. `final = true` запрещает удержание: всё, что
   * осталось, обязано быть отдано (поток кончился, ждать больше нечего).
   */
  function scan(final) {
    const events = [];
    let pending = '';     // текст, накопленный до ближайшего тега
    let i = 0;

    const flushText = () => {
      if (pending) { events.push({ type: 'text', text: pending }); pending = ''; }
    };

    while (i < buf.length) {
      const lt = buf.indexOf('<', i);
      if (lt === -1) { pending += buf.slice(i); i = buf.length; break; }

      pending += buf.slice(i, lt);

      TAG_AT.lastIndex = lt;
      const m = TAG_AT.exec(buf);
      if (m) {
        const end = lt + m[0].length;
        // Совпадение упирается в конец буфера и не съело перевод строки:
        // следующим событием может приехать '\n', который по грамматике
        // принадлежит ТЕГУ, а не тексту секции. Держим тег до прояснения —
        // иначе нарезка потока влияла бы на результат разбора.
        if (!final && end === buf.length && !m[0].endsWith('\n')) { i = lt; break; }

        flushText();
        if (m[1] === '/') {
          // Закрывающий без открытой секции — разметка сломана; лишнее
          // событие только сбило бы потребителя, текст при этом не теряется.
          if (openSection !== null) { events.push({ type: 'section_end' }); openSection = null; }
        } else {
          // Вложенность моделью не предусмотрена, но встречается в сломанной
          // разметке. Закрываем предыдущую сами: потребителю проще получить
          // сбалансированный поток, чем разбираться со вложенностью.
          if (openSection !== null) events.push({ type: 'section_end' });
          openSection = m[2] ?? '';
          events.push({ type: 'section_start', name: openSection });
        }
        i = end;
        continue;
      }

      // Полного совпадения нет. Либо тег ещё набирается — держим хвост
      // (без порога длины, см. шапку файла), либо это обычный '<' в тексте.
      if (!final && couldBeTagPrefix(buf.slice(lt))) { i = lt; break; }
      pending += '<';
      i = lt + 1;
    }

    buf = buf.slice(i);
    flushText();
    return events;
  }

  return {
    /** Скормить очередное событие потока. Возвращает события разбора. */
    push(chunk) {
      if (!chunk) return [];
      buf += chunk;
      return scan(false);
    },

    /**
     * Поток кончился ([DONE] или обрыв). Отдаёт остаток и закрывает секцию,
     * если модель этого не сделала (обрезка по длине — легальный случай, §4
     * п. 6: текст терять нельзя).
     */
    end() {
      const events = scan(true);
      if (openSection !== null) { events.push({ type: 'section_end' }); openSection = null; }
      return events;
    },
  };
}
