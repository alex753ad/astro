/**
 * FeedTimelineNode.jsx — один узел вертикальной линии времени (§2-3
 * SPEC_FEED_VISUAL.md, «Заход А»: скелет структуры, карточки не трогаем).
 *
 * Колонка времени слева (64 px) + линия + точка + содержимое справа.
 *
 * Содержимое — это ЦЕЛИКОМ существующий children (FeedEventCard как есть,
 * либо FeedLunarFold без своей точки — см. `dot={null}` у вызывающего).
 *
 * ⚠️ `fill` — цвет СЕРДЦЕВИНЫ точки, а не обводки: точка это кольцо, и
 * внутри него лежит фон той поверхности, на которой она стоит. По умолчанию
 * это --bg-dot; раскрытый день ленты лежит на поднятой поверхности
 * (`--bg-card`) и передаёт её сюда. В светлой теме разница почти не видна
 * (#FFFFFF против #FFFFFF), в ТЁМНОЙ видна сразу (#0F0A1A против #1A1230):
 * сердцевина оказалась бы темнее карточки, то есть дыркой в ней.
 *
 * ⚠️ Токен, а не `var(--bg)`, с 15.09.2026: фон страницы в светлой теме стал
 * ГРАДИЕНТОМ, и плоский цвет под точку из него не берётся — любой попадёт
 * мимо. --bg-dot задан отдельно (белый в светлой, цвет фона в тёмной).
 *
 * ⚠️ Линия — не один элемент на весь экран, а сегмент на каждый узел
 * (`position:absolute; top:0; bottom:0` внутри `position:relative`-обёртки,
 * которая включает и paddingBottom узла). Это даёт непрерывную линию
 * ВНУТРИ дня — соседние узлы стыкуются день без зазора, потому что зазор
 * между ними — это paddingBottom текущего узла, а не внешний gap
 * контейнера, и абсолютный элемент с top:0/bottom:0 растягивается на всю
 * область узла, padding включительно.
 *
 * Линия рвётся на заголовке дня (`FeedDayHeader.jsx`) — он живёт вне узла и
 * линии не рисует. Непрерывность через день — открытый пункт устройства
 * (§10), не решённый здесь архитектурно. (Заголовок был липким до
 * 15.09.2026; на разрыв линии это не влияло ни тогда, ни сейчас.)
 *
 * ⚠️ Отдельного маркера «СЕГОДНЯ» больше нет (был `FeedTodayMarker.jsx`,
 * убран 06.09.2026) — метка дублировала «Сегодня · …» в самом заголовке
 * дня (`dayLabel()`, feedTime.js) и не показывалась вовсе, когда сегодня —
 * первый день окна. Заголовок покрывает оба случая одной строкой.
 */

import React from 'react';

/*
 * ⚠️ 48, а не 64 (приёмка 16.09.2026). Шестнадцать пикселей отданы
 * РАСШИФРОВКЕ: внутри карточки «Сегодня» период зажат с трёх сторон — поля
 * карточки дня, колонка времени и своя рамка, — и текст рекомендаций рвался
 * на три-четыре строки там, где помещался в две.
 *
 * ⚠️ 48 — не «сколько не жалко», а замер: «22:06» кеглем 12/700 занимает 31px,
 * плюс правый отступ 14 и запас 3 на увеличенный системный шрифт Android
 * (он масштабирует ВЕСЬ текст WebView, см. §5 DESIGN_SYSTEM.md). Уже — и
 * время начнёт переноситься; ширина у него фиксированная, и перенос там
 * ломает выравнивание всей колонки, а не одну строку.
 *
 * ⚠️ Значение одно на ВСЕ дни, включая раскрытый. Разная колонка в разных
 * днях означала бы, что вертикальная линия прыгает влево-вправо при
 * прокрутке — она сквозная, и это видно сразу.
 */
const TIME_COL_WIDTH = 48;
const LINE_LEFT = TIME_COL_WIDTH - 1;

export default function FeedTimelineNode({
  time, bold, color, size, children, gap = 12, fill = 'var(--bg-dot)', dense = false,
  quiet = false, solid = false,
}) {
  const hasDot = typeof size === 'number';
  return (
    <div style={{ position: 'relative', paddingBottom: gap }}>
      <span
        style={{
          position: 'absolute',
          left: LINE_LEFT,
          top: 0,
          bottom: 0,
          width: 1,
          /* ⚠️ `--text-secondary`, а не `--border`, и это не «поярче ради
             красоты». `--border` в светлой теме — #EDE8F5, а фон страницы в
             приложении градиентный и начинается с #f8f0ff: контраст линии
             1.06:1, то есть линии нет вовсе (приёмка 16.09.2026). Токена
             «видно на светлом, тихо на тёмном» в §2 не существует —
             `--accent-hairline` и `--accent-mark` в светлой разворачиваются в
             тот же `--border`. Взят `--text-secondary`: линия становится ровно
             настолько заметной, насколько заметен вспомогательный текст рядом
             с ней, — и в обеих темах одинаково, без нового цвета и без
             значения на тему. */
          background: 'var(--text-secondary)',
          opacity: 0.6,
        }}
      />
      {hasDot && (
        <span
          style={{
            position: 'absolute',
            left: LINE_LEFT,
            top: 6,
            width: size,
            height: size,
            borderRadius: '50%',
            /* ⚠️ `solid` — период планера: кружок ЗАЛИТ цветом планеты, а не
               обведён им (решение владельца 16.09.2026). Полый кружок у
               периода читался как «ещё одно событие», а период — носитель
               цвета: тот же цвет стоит у его значка и в полосе шапки.
               У транзитов кружок остаётся полым, их не трогаем. */
            background: solid ? color : fill,
            border: solid ? 'none' : `${size >= 13 ? 2 : 1.5}px solid ${color}`,
            transform: 'translate(-50%, 0)',
            opacity: quiet ? 0.62 : 1,
          }}
        />
      )}
      {/* minHeight:44 — только когда есть точка на линии, под которую эта
          высота и подобрана (§3): она держит первую строку КАРТОЧКИ вровень
          с точкой.

          ⚠️ `dense` снимает её у сжатой строки дня (FeedEventRow.jsx): та
          высотой около 22px, и 44 превращались в 20px пустоты под КАЖДОЙ
          строкой. Заметно это именно в прошлом и будущем, где сжатых дней
          подряд идут десятки, — то есть там, где ритм и проверяется. У безточечного узла (свёртка лунных, dot={null}/time="")
          она была чистым принудительным зазором — растягивала flex-строку
          с align-items:stretch по умолчанию до 44px, хотя сама кнопка
          свёртки высотой ~28px, и это 16px пустоты плюс paddingBottom узла
          читались как двойной отступ. */}
      <div style={{ display: 'flex', minHeight: (hasDot && !dense) ? 44 : undefined }}>
        <div
          style={{
            width: TIME_COL_WIDTH,
            flexShrink: 0,
            textAlign: 'right',
            paddingRight: 14,
            fontFamily: 'var(--font-body)',
            fontVariantNumeric: 'tabular-nums',
            fontSize: bold ? 12 : 11,
            fontWeight: bold ? 700 : 400,
            color: bold ? 'var(--text-primary)' : 'var(--text-secondary)',
            paddingTop: 2,
            // `quiet` приходит вместе с приглушённой строкой события
            // (лунный фон): время и точка — часть той же строки, и
            // оставить их в полную силу значит приглушить половину.
            opacity: quiet ? 0.62 : 1,
          }}
        >
          {time}
        </div>
        <div style={{ flex: 1, minWidth: 0, paddingLeft: 16 }}>
          {children}
        </div>
      </div>
    </div>
  );
}
