/**
 * BlurredHint.jsx — витрина закрытого содержимого под блюром.
 *
 * Один компонент на два места: развёрнутый чип полосы «сейчас»
 * (FeedNowStrip.jsx) и карточка периода планера в потоке
 * (FeedEventCard.jsx). Пейволльная витрина — тот случай, где две копии
 * разъезжаются молча: правят текст в одном месте, а второе продолжает
 * обещать другое.
 *
 * Строки — заведомо обобщённые формулировки, а не настоящие рекомендации:
 * на free сервер отдаёт `groups: []`, то есть показывать под блюром нечего,
 * и подставлять сюда чужой реальный текст было бы обманом. Смысл блока —
 * показать ФОРМУ закрытого содержимого, а не его подобие.
 *
 * aria-hidden: для читалки это декорация. Незрячему пользователю размытые
 * буквы не несут ничего, а объявлять их как текст — значит зачитывать
 * приманку вместо содержания.
 */

import React from 'react';

const LINES = [
  'Ставьте цели на будущее и корректируйте курс',
  'Расширяйте круг общения',
  'Работайте с технологиями',
];

export default function BlurredHint() {
  return (
    <div aria-hidden="true" style={{ filter: 'blur(4px)', opacity: 0.5, userSelect: 'none' }}>
      {LINES.map((line) => (
        <p key={line} style={{ margin: '0 0 6px', fontSize: 13, lineHeight: 1.5, color: 'var(--text-secondary)' }}>
          {line}
        </p>
      ))}
    </div>
  );
}
