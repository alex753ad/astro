/**
 * FeedDayHeader.jsx — липкий заголовок дня в ленте (§6 спецификации).
 *
 * `position: sticky` прилипает к верху БЛИЖАЙШЕГО прокручиваемого предка, а
 * он живёт не здесь: скроллер один на все три вкладки и находится в
 * TabShell.jsx. Отсюда два следствия, которые легко нарушить правкой рядом:
 *
 *   1. Заголовок обязан быть непрозрачным (`background: var(--bg)`).
 *      Прилипший прозрачный заголовок пропускает под собой карточки, и
 *      текст накладывается на текст. Прозрачность тут не украшение, а
 *      поломка.
 *   2. Ни один предок заголовка внутри FeedScreen не должен получить
 *      `overflow` (`auto`/`hidden`/`scroll`) — это создаст новый контекст
 *      прокрутки, и sticky начнёт липнуть к нему, то есть перестанет
 *      липнуть к экрану вовсе. Ошибка тихая: вёрстка выглядит целой,
 *      просто заголовки уезжают вверх вместе с потоком.
 *
 * z-index нужен, потому что карточки идут в потоке ПОСЛЕ заголовка: без
 * него следующая карточка перекрывала бы прилипший заголовок при прокрутке.
 */

import React from 'react';

export default function FeedDayHeader({ label }) {
  return (
    <h2
      style={{
        position: 'sticky',
        top: 0,
        zIndex: 1,
        margin: 0,
        padding: '10px 0 8px',
        background: 'var(--bg)',
        color: 'var(--text-secondary)',
        fontFamily: 'var(--font-display)',
        fontSize: 13,
        fontWeight: 600,
      }}
    >
      {label}
    </h2>
  );
}
