/**
 * FeedDayHeader.jsx — граница суток в ленте.
 *
 * С 15.09.2026 день в ленте — БЛОК, а не строка в потоке (DESIGN_SYSTEM.md §5,
 * решение владельца по образцу `frontend/feed-rhythm-specimen.html`). Заголовок
 * из подписи 13px того же цвета, что строки внутри карточек, стал границей:
 * дата антиквой, день недели капителью гротеска, линия и воздух до и после.
 *
 * ⚠️ Заголовок — носитель ритма на большей части ленты, и это измерено, а не
 * предположено: в боевой выдаче 68 дней из 148 не содержат ни одной карточки
 * (50 из них — вообще только лунный фон), самая длинная серия дней подряд без
 * карточки — шесть. То есть экран, целиком состоящий из сжатых строк, —
 * обычное состояние ленты, а не край. Ослабить заголовок «потому что рядом и
 * так есть карточки» нельзя: рядом их нет.
 *
 * ⚠️ Блок обязан быть пропорционален содержанию (`quiet`): у дня, где кроме
 * лунного фона ничего нет, нижнего отступа почти не остаётся. Иначе полсотни
 * одинаковых пустых дней дают ровную гребёнку — ту же массу, из которой
 * уходили, только собранную из заголовков.
 *
 * ⚠️ ЛИПКОСТИ ЗДЕСЬ БОЛЬШЕ НЕТ — решение владельца 15.09.2026, и это не
 * упрощение по дороге, а отказ от приёма, который перестал окупаться.
 *
 * `position: sticky` жил здесь с первого захода, когда заголовок был
 * единственным признаком дня. Сегодня день читается блоком, а «какой день я
 * смотрю» при длинной прокрутке отвечает компактная полоса сверху
 * (FeedNowCompact.jsx) — она же показывает дату дня, стоящего у верхней
 * кромки.
 *
 * Что липкость ломала, пока была: прилипший заголовок обязан быть
 * непрозрачным, иначе под ним едет текст. До градиента это была полоса во всю
 * ширину; с градиентом (15.09.2026) полоса стала читаться светлой заплаткой
 * поперёк фона, и её заменили чипом по ширине текста. Чип перекрывал уже не
 * всю строку, а её ЧАСТЬ — и на приёмке это поймали как дефект: заголовок
 * карточки периода уезжал под чип, а справа торчал огрызок слова. Отступом
 * такое не лечится: sticky по определению плывёт над содержимым и высоты под
 * себя не занимает.
 *
 * ⚠️ Поэтому не возвращать sticky сюда «чтобы было видно, какой это день»:
 * вернётся вместе с ним и перекрытие. Дату показывает полоса сверху.
 */

import React from 'react';
import { dayDate, dayLabel, isMonthStart, monthTitle, weekdayLong } from '../lib/feedTime';

const LABEL_STYLE = {
  fontFamily: 'var(--font-body)',
  fontSize: 11,
  fontWeight: 700,
  letterSpacing: '0.09em',
  textTransform: 'uppercase',
  color: 'var(--text-secondary)',
};

/**
 * `boundary` — обычный день в потоке: линия-граница, воздух до и после.
 * `false` — заголовок внутри раскрытого дня, лежащего на поднятой поверхности
 * (FeedScreen.jsx): там границу рисует сама поверхность, вторая черта внутри
 * неё была бы повтором.
 */
export default function FeedDayHeader({ date, today, first = false, quiet = false, boundary = true }) {
  const isToday = date === today;
  const monthStep = isMonthStart(date) && !first;
  return (
    <header
      aria-label={dayLabel(date, today)}
      style={boundary ? {
        // Ступень месяца — тот же приём, что и у дня, на порядок крупнее:
        // добавочный воздух. Своих цветов и линий ей не заводили.
        marginTop: first ? 8 : (monthStep ? 44 : 26),
        paddingBottom: quiet ? 4 : 12,
      } : {
        paddingBottom: 14,
      }}
    >
      {monthStep && (
        <div style={{ ...LABEL_STYLE, letterSpacing: '0.12em', marginBottom: 8 }}>
          {monthTitle(date, today)}
        </div>
      )}
      {boundary && (
        <div
          style={{
            height: isToday ? 2 : 1,
            background: isToday ? 'var(--accent)' : 'var(--border)',
            marginBottom: 10,
          }}
        />
      )}
      {isToday && (
        <div style={{ ...LABEL_STYLE, letterSpacing: '0.12em', color: 'var(--accent)', marginBottom: 2 }}>
          Сегодня
        </div>
      )}
      <div style={{ display: 'flex', alignItems: 'baseline', gap: 10 }}>
        <h2
          style={{
            margin: 0,
            fontFamily: 'var(--font-display)',
            fontSize: boundary ? 21 : 24,
            fontWeight: 700,
            lineHeight: 1.15,
            color: 'var(--text-primary)',
          }}
        >
          {dayDate(date)}
        </h2>
        <span style={LABEL_STYLE}>{weekdayLong(date)}</span>
      </div>
    </header>
  );
}
