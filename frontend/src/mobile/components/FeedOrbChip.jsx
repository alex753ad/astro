/**
 * FeedOrbChip.jsx — орб транзита чипом, точность — заливкой.
 *
 * Вынесен из FeedEventCard.jsx 15.09.2026, когда у рядового события в сжатом
 * дне появилась вторая форма показа (FeedEventRow.jsx): правило «точный —
 * сплошной акцент, иначе рамка» обязано быть одно на обе формы. Двумя копиями
 * оно разъехалось бы при первой же правке порога, причём заметно это стало бы
 * только в одном из двух мест.
 *
 * ⚠️ У чипа порога по орбу НЕТ вовсе: «точный» здесь означает `applying`, то
 * есть аспект сходится, а не расходится — так было с первого захода, и при
 * выносе это поведение сохранено дословно. Порог 0.05° живёт в feedRank.js и
 * отвечает на ДРУГОЙ вопрос: получает ли событие карточку в сжатом дне.
 * Приписать порог сюда «для единообразия» нельзя — сегодня заливку получает
 * и сходящийся аспект с орбом 0.5°, и это принятое состояние.
 *
 * ⚠️ Точность — заливкой, а не отдельной строкой «точный» под каждым
 * транзитом: при 700+ событиях это была треть высоты ленты на одно слово. И не
 * точкой: точка акцентом уже занята под «разбор открыт» — два одинаковых
 * значка с разным смыслом в одной строке неотличимы друг от друга.
 *
 * ⚠️ Белый текст на акценте — литералом, и это уже принятое по всему
 * приложению исключение (.mobile-btn-primary, «сегодня» в FeedDayStrip.jsx), а
 * не новое. Заливка var(--accent-muted) (8% альфы) здесь стояла раньше и
 * оказалась неразличима: тон почти не отличался от фона карточки.
 */

import React from 'react';

export default function FeedOrbChip({ meta }) {
  if (!meta || typeof meta.peak_orb !== 'number') return null;
  const precision = typeof meta.applying === 'boolean'
    ? (meta.applying ? 'точный' : 'отходит')
    : null;
  const exact = precision === 'точный';

  return (
    <span
      title={precision || undefined}
      style={{
        padding: '2px 7px',
        border: `1px solid ${exact ? 'var(--accent)' : 'var(--border)'}`,
        borderRadius: 'var(--radius-sm)',
        fontSize: 10.5,
        fontWeight: exact ? 700 : 400,
        fontFamily: 'var(--font-body)',
        background: exact ? 'var(--accent)' : 'transparent',
        color: exact ? '#fff' : 'var(--text-secondary)',
      }}
    >
      {meta.peak_orb.toFixed(1)}°
    </span>
  );
}
