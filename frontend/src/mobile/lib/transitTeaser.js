/**
 * transitTeaser.js — одна строка про КОНКРЕТНЫЙ транзит, собранная из данных.
 *
 * ⚠️ Что было до 09.09.2026. Сервер отдавал одну и ту же фразу на все события
 * подряд («Это активный период по одной из ключевых тем вашей карты…»,
 * `feed/templates.json`). Продать она не могла: о самом транзите там нет
 * ничего, и человек, открывший десять карточек, десять раз читал одно и то
 * же. Здесь она заменяется строкой, собранной из `meta` конкретного события.
 *
 * ⚠️ Ноль запросов и ноль расхода квоты: к модели не обращаемся вовсе. Тизер
 * — это перечисление того, что уже пришло в ленте, а не разбор.
 *
 * ⚠️ ТРАКТОВКИ ЗДЕСЬ НЕТ, и это граница, а не недоделка (решение владельца).
 * Говорим, ЧТО за транзит и какого он характера; что с этим делать и как оно
 * проявится — остаётся платному разбору. Ни одного «стоит», «лучше»,
 * «избегайте».
 *
 * ⚠️ Собирается из частей: своя тема на планету, свой хвост на аспект. Списка
 * фраз на пару планет нет и быть не должно — пар больше сотни, и такой список
 * пришлось бы дописывать при каждом новом объекте.
 *
 * ⚠️ Чего нет в `meta`, не выдумываем. Не хватило данных на осмысленную фразу
 * — возвращаем `null`, и панель показывает прежний общий текст сервера. Лучше
 * общая правда, чем частное правдоподобие.
 */

import { planetRu } from './feedTime';
import { planetDativeRu } from './ruDeclension';

/**
 * Тема планеты в родительном падеже — под подстановку «тема X и Y».
 *
 * По одному слову на объект, а не фраза на пару: пар больше сотни. Слова
 * намеренно нейтральные и без оценки — «иллюзий», а не «обмана»; «границ», а
 * не «ограничений». Оценку даёт разбор, не тизер.
 */
const PLANET_THEME = {
  Sun: 'ясности',
  Moon: 'чувств',
  Mercury: 'слов',
  Venus: 'близости',
  Mars: 'действия',
  Jupiter: 'роста',
  Saturn: 'границ',
  Uranus: 'перемен',
  Neptune: 'иллюзий',
  Pluto: 'глубины',
  'North Node': 'направления',
  'South Node': 'привычного',
};

/**
 * Характер аспекта — без трактовки, только тип связи.
 *
 * «Напряжённый» и «мягкий» — принятые в астрологии названия групп, а не
 * оценка «плохо/хорошо»: у напряжённого аспекта нет обещания беды, как у
 * мягкого нет обещания удачи. Именно поэтому здесь не «сложный» и не
 * «удачный».
 */
const ASPECT_KIND = {
  conjunction: 'Соединение',
  opposition: 'Напряжённый аспект',
  square: 'Напряжённый аспект',
  trine: 'Мягкий аспект',
  sextile: 'Мягкий аспект',
};

/**
 * Типичная длительность окна транзита — по ТРАНЗИТНОЙ планете.
 *
 * ⚠️ Это единственное в строке, чего нет в `meta`, и об этом надо знать.
 * Лента не отдаёт границ транзита ВООБЩЕ: `ends_at` и `duration_days` у него
 * `null`, а `start_date`/`end_date` сервер не присылает, потому что они
 * обрезаны окном запроса и показывать их как «начало» и «конец» нельзя
 * (CLAUDE.md, раздел про ленту).
 *
 * Поэтому здесь не расчёт по датам события, а свойство самой планеты — её
 * скорость. Оно такая же статика, как название и тема, и потому же
 * допустимо. Слово «около» в тексте не украшение: оно и означает, что это
 * порядок величины, а не срок этого конкретного события.
 *
 * Понадобится точное окно — его должна прислать лента, и это отдельная
 * работа на бэкенде.
 */
const TRANSIT_WINDOW = {
  Moon: 'окно несколько часов',
  Sun: 'окно около недели',
  Mercury: 'окно около недели',
  Venus: 'окно около недели',
  Mars: 'окно около двух недель',
  Jupiter: 'окно около месяца',
  Saturn: 'окно несколько месяцев',
  Uranus: 'окно до года',
  Neptune: 'окно до года',
  Pluto: 'окно до года',
  'North Node': 'окно несколько недель',
  'South Node': 'окно несколько недель',
};

/**
 * Где планета находится относительно СВОЕЙ натальной точки.
 *
 * ⚠️ Нужно потому, что фраза построена на паре тем, а когда транзитная и
 * натальная планета совпадают, пара схлопывается и остаётся половина
 * конструкции: «Луна к вашей Луне: тема чувств» читается обрублено. На боевых
 * лентах таких событий около 8% (64–71 из ~800 на карту, замер по пяти
 * картам) — не редкость, которой можно пренебречь.
 *
 * ⚠️ «Возвращение» подходит ТОЛЬКО соединению, и это главное, что здесь легко
 * сделать неправильно. Тот же замер: у совпадающих пар встречаются все пять
 * аспектов, и соединений среди них меньшинство (6–7 из ~65). Луна в квадрате
 * к своей натальной Луне никуда не возвращается — она проходит четверть
 * собственного круга. Назвать это возвращением значило бы соврать в трети
 * случаев.
 *
 * Формулировки описывают механику, а не последствия: где планета в своём
 * круге. Что это значит для человека — остаётся платному разбору.
 *
 * ⚠️ Тригон и секстиль намеренно дают ОДНУ формулировку, хотя это разные
 * точки круга (120° и 60°). Развести их можно было бы только долей — «треть»
 * и «шестая часть», — а вводить дроби владелец запретил 09.09.2026: это уже
 * терминология, а не язык. Общая формулировка честнее ложной точности: она
 * говорит ровно то, что есть, — планета не в ключевой точке.
 *
 * ⚠️ Здесь стояла «промежуточная точка», и её пришлось заменить. Слово
 * канцелярское, а достаётся оно самому частому случаю на ленте: тригон и
 * секстиль дают 169 строк из 333 у совпадающих пар (замер 09.09.2026, пять
 * карт, окно 180 дней). Убрать фазу у этих двух аспектов вовсе — второй
 * рассмотренный вариант — вернуло бы «Луна к вашей Луне: тема чувств» той
 * самой половине событий, ради которой фаза и заводилась.
 */
const SELF_CYCLE_PHASE = {
  conjunction: 'начало',
  opposition: 'середина',
  square: 'четверть',
  trine: 'между ключевыми точками',
  sextile: 'между ключевыми точками',
};

/**
 * Тема пары. `null`, если планеты совпали — такому случаю нужен свой хвост
 * (см. `SELF_CYCLE_PHASE`), а не половина парной конструкции.
 */
function pairTheme(transitPlanet, natalPlanet) {
  const a = PLANET_THEME[transitPlanet];
  const b = PLANET_THEME[natalPlanet];
  if (!a || !b) return null;
  if (a === b) return null;
  return `${a} и ${b}`;
}

/**
 * Строка тизера или `null`, если данных не хватило.
 *
 * @param {object} event — событие ленты
 * @returns {string|null}
 */
export function transitTeaserText(event) {
  if (event?.kind !== 'transit') return null;
  const meta = event.meta || {};

  const subject = planetRu(meta.transit_planet);
  const target = planetDativeRu(meta.natal_planet);
  const kind = ASPECT_KIND[meta.aspect_type];
  const window = TRANSIT_WINDOW[meta.transit_planet];
  const own = meta.transit_planet === meta.natal_planet;
  const theme = own
    ? PLANET_THEME[meta.transit_planet]
    : pairTheme(meta.transit_planet, meta.natal_planet);
  const phase = own ? SELF_CYCLE_PHASE[meta.aspect_type] : null;

  // Любая недостающая часть — отказ целиком. Строка без темы или без
  // характера аспекта хуже прежней общей фразы: она выглядит осмысленной и
  // при этом ничего не сообщает.
  if (!subject || !target || !theme || !kind || !window) return null;
  if (own && !phase) return null;
  if (subject === meta.transit_planet) return null;   // planetRu вернул ключ — имени нет

  // Планета пришла к своей же точке: пары тем нет, есть положение в
  // собственном круге. Форма та же, слот темы занят фазой цикла.
  //
  // ⚠️ Слово «тема» здесь обязательно, хотя без него короче. Проверено
  // 09.09.2026 на всех совпадающих парах словаря: «собственного цикла
  // привычного» (Южный узел) не читается вовсе, «собственного цикла слов»
  // (Меркурий) читается как «цикл слов» — то есть тема начинает выглядеть
  // свойством цикла, а не планеты. Плюс три родительных падежа подряд.
  // «Тема» разрывает цепочку и возвращает слову роль перечисления.
  if (own) {
    return `${subject} к ${target}: ${phase} собственного цикла, тема ${theme}. ${kind}, ${window}.`;
  }

  return `${subject} к ${target}: тема ${theme}. ${kind}, ${window}.`;
}
