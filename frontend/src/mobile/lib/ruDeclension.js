/**
 * ruDeclension.js — склонение русских слов под подстановку, общий помощник
 * для мобильного фронтенда.
 *
 * Заведён 06.09.2026, когда таких мест на фронтенде стало два: предложный
 * падеж знака зодиака (`signInRu`, жил в feedTime.js, ленте нужен для «Луна
 * в Деве») и предложный падеж названия тарифа (`tierInRu`, жил в
 * FeedHorizonCard.jsx как локальный `inTier`, нужен для «Открывается на
 * Веге»). CLAUDE.md фиксировал это ещё с двух мест — `_plural()`
 * (backend/email_service.py, склонение числительных) и `inTier()` — и
 * заранее оговаривал: они не сводятся в одно, потому что живут в разных
 * рантаймах (Python/JS) и склоняют разные категории слов (числа/тарифы).
 * Тот вывод не отменяется — бэкендный `_plural()` остаётся отдельно. Но
 * ДВА фронтендных случая — из одного рантайма, и не иметь для них общего
 * места означало бы, что третий такой случай на фронтенде снова начнут
 * искать копированием готовой функции в новый файл, как уже было один раз.
 * 06.09.2026 добавился третий — винительный падеж тарифа (`tierAccusative`,
 * экран «Ещё»): нашёлся здесь, а не копированием `tierInRu` в новый файл.
 *
 * Оба словаря — не алгоритм. У знаков зодиака 12 исключений из общих схем
 * (Телец → Тельце, Лев → Льве, чередование гласной) — проще перечислить,
 * чем угадывать правилом. У тарифов правило проще (только женский род на
 * «а» и мужской без окончания), но сетка из четырёх названий не длиннее
 * прямого перечисления, а перечисление не сломается, если однажды появится
 * тариф, для которого суффиксное правило не сработает.
 */

/**
 * Предложный падеж знака — «Луна в Деве», «до новолуния в Рыбах» (§6
 * SPEC_FEED_VISUAL.md ленты). Именительный (`signRu` в feedTime.js) для
 * фразы с «в» не подходит: «в Дева» — не по-русски.
 *
 * ⚠️ Ключи — и английские, и русские именительные. Один и тот же по смыслу
 * `meta.sign` приходит в РАЗНОМ виде в зависимости от события: у транзита
 * (`meta.transit_sign`) — английским («Virgo»), а у фазы Луны (`meta.sign`,
 * `feed/builder.py`, `_sign()` в блоке фаз) — уже русским («Дева»), потому
 * что тем же значением бэкенд собирает готовую фразу `text` фазы.
 * Расхождение источника, не опечатка: чинить его — на бэкенде, отдельной
 * задачей; здесь — принять оба входа, раз оба реально приходят.
 */
const SIGN_PREPOSITIONAL = {
  Aries: 'Овне', Taurus: 'Тельце', Gemini: 'Близнецах', Cancer: 'Раке',
  Leo: 'Льве', Virgo: 'Деве', Libra: 'Весах', Scorpio: 'Скорпионе',
  Sagittarius: 'Стрельце', Capricorn: 'Козероге', Aquarius: 'Водолее',
  Pisces: 'Рыбах',
  Овен: 'Овне', Телец: 'Тельце', Близнецы: 'Близнецах', Рак: 'Раке',
  Лев: 'Льве', Дева: 'Деве', Весы: 'Весах', Скорпион: 'Скорпионе',
  Стрелец: 'Стрельце', Козерог: 'Козероге', Водолей: 'Водолее', Рыбы: 'Рыбах',
};

import { signRu } from './feedTime';

/** Если знака нет в словаре предложного падежа (не должно случаться на
 * 12 знаках) — откат на именительный, а не на пустую строку. */
export function signInRu(sign) {
  return SIGN_PREPOSITIONAL[sign] || signRu(sign);
}

/**
 * Предложный падеж названия тарифа: «на Веге», «на Лире», «на Орионе».
 *
 * Названия приходят с бэкенда в именительном (Вега, Лира, Орион). Женские
 * на «а» меняют её на «е», мужские получают «е» в конец. Без склонения
 * выходило «на Вегае» — приписать окончание к неизменённой форме мало.
 */
export function tierInRu(name) {
  return name.endsWith('а') ? `${name.slice(0, -1)}е` : `${name}е`;
}

/**
 * Винительный падеж названия тарифа: «на Вегу», «на Лиру», «на Орион»
 * (экран «Ещё», SPEC_MORE_SCREEN.md §4). Третий случай, предсказанный в
 * шапке файла — падеж другой (винительный, не предложный), поэтому не
 * вариант `tierInRu`, а сосед: женские на «а» меняют её на «у», мужские
 * (Орион) в винительном для неодушевлённого не меняются вовсе.
 */
export function tierAccusative(name) {
  return name.endsWith('а') ? `${name.slice(0, -1)}у` : name;
}
