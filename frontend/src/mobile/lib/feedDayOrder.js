/**
 * feedDayOrder.js — что и в каком порядке рисуется внутри дня ленты.
 *
 * ⚠️ Правило одно: **события идут строго по времени** (решение владельца
 * 16.09.2026). Единственное исключение — свёртка лунного фона: она не событие,
 * а СТРОКА-ИТОГ по нескольким событиям сразу, и своего времени у неё нет.
 * Поэтому она стоит внизу дня.
 *
 * ⚠️ Зачем отдельный файл. До 16.09.2026 день рисовался в два прохода:
 * сначала всё «не фон», потом лунный фон. При двух и более лунных это давало
 * свёртку внизу — как и задумано, — но при ОДНОМ лунном событии оно тоже
 * уезжало в конец дня, независимо от времени. В сегодняшнем дне это было видно
 * прямо: «19:33 Луна в 3 доме», а под ним «07:56 Луна — Сатурн».
 *
 * Прежнее поведение было записано как решение (15.09.2026, FeedEventRow.jsx):
 * довод был в предсказуемости — «одно лунное стояло бы в потоке, два и больше
 * уезжали бы вниз». Приёмка показала, что читается это не как правило, а как
 * сбой сортировки, и решение отменено. Предсказуемость осталась у СВЁРТКИ: она
 * внизу всегда.
 *
 * Порядок внутри `events` не пересчитывается: его задаёт сервер
 * (`max(at, from_date)`, затем `at`, затем `key` — см. build_feed), и второй
 * сортировки на клиенте быть не должно. Здесь только разделение на то, что
 * идёт в поток, и то, что уходит под свёртку.
 */

import { isLunarBackground } from '../components/FeedLunarFold';

/**
 * @param {{events: object[]}} day — день ленты, события уже по возрастанию `at`.
 * @returns {{inFlow: object[], folded: object[]}}
 *   `inFlow` — по времени, вперемешку с лунным фоном, если он одиночный;
 *   `folded` — под свёртку (пусто, если лунных меньше двух).
 */
export function splitDayEvents(day) {
  const events = day?.events || [];
  const background = events.filter(isLunarBackground);

  // Одно лунное сворачивать не во что: «ещё 1 лунное» ничего не сокращает,
  // только добавляет лишний тап. Оно остаётся событием и встаёт по времени.
  if (background.length < 2) return { inFlow: events, folded: [] };

  return {
    inFlow: events.filter((e) => !isLunarBackground(e)),
    folded: background,
  };
}
