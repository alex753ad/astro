/**
 * plannerItemLabel.js — метка в начале строки рекомендации («Быт:», «Дела:»).
 *
 * ⚠️ Зачем это вообще нужно: методичка хранит метку ДВУМЯ разными способами, и
 * различие видно на экране. У Меркурия и большинства планет группа несёт
 * `heading` («Проверка и учёт документов:»), и он рисуется отдельной жирной
 * строкой. У Луны `heading` пустой, а метка вшита в САМ пункт: «Работа: наведи
 * порядок…». Из-за этого на одном экране период Меркурия показывал жирные
 * подписи, а период Луны — те же подписи в подбор и обычным весом.
 *
 * Разница в ДАННЫХ (backend/transit/methodology.json), и чинить её там значило
 * бы переписывать методичку — тексты владельца. Поэтому метка выделяется при
 * отрисовке: из пункта берётся то, что стоит до первого двоеточия.
 *
 * ⚠️ Ограничения нарочно строгие, иначе жирным станет половина предложения:
 * метка обязана быть короткой, стоять в начале и не содержать знаков конца
 * предложения. Двоеточие в середине фразы («…: список») меткой не считается.
 */

/** Сколько символов допускается в метке. Длиннее — это уже фраза, не подпись. */
const MAX_LABEL = 28;

/**
 * Разобрать пункт на метку и остальное.
 *
 * @returns {{label: string, rest: string}} `label` пустой, если метки нет.
 */
export function splitItemLabel(item) {
  const text = typeof item === 'string' ? item : '';
  const at = text.indexOf(':');
  if (at <= 0 || at > MAX_LABEL) return { label: '', rest: text };

  const label = text.slice(0, at);
  // Точка, запятая и прочие разделители внутри — признак, что это не подпись,
  // а кусок предложения, которому двоеточие досталось случайно.
  if (/[.!?;,]/.test(label)) return { label: '', rest: text };

  return { label: `${label}:`, rest: text.slice(at + 1).trim() };
}
