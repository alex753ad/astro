/**
 * localNotificationPlan.js — превращает выдачу `GET /api/v1/push/upcoming`
 * в список локальных уведомлений, которые надо поставить на устройстве.
 *
 * Отдельный файл от `localNotifications.js` намеренно: здесь нет ни одного
 * обращения к Capacitor, поэтому всё правило целиком проверяется обычным
 * прогоном тестов, без устройства и без эмулятора. На устройстве остаётся
 * только «поставить то, что насчитано».
 *
 * ⚠️ Главная граница этого файла: КЛИЕНТ СКЛЕИВАЕТ СПИСОК, НО НЕ СОЧИНЯЕТ
 * ТЕКСТ (решение владельца 10.09.2026, docs/HISTORY-push.md). Ручка отдаёт
 * готовые `title`/`body`, и ни одно слово здесь к ним не дописывается:
 * единственные символы, которые добавляет этот файл, — разделители (перевод
 * строки и « · », тот же, которым склеивает веб-планировщик). Появится здесь
 * своя формулировка — появится второй источник текстов уведомлений, ровно то,
 * ради чего ручка и делалась.
 *
 * ⚠️ У ВРЕМЕНИ ЭТО ПРАВИЛО ТАКОЕ ЖЕ, и именно так сделан запас у верхней
 * границы окна (ниже): клиент НИКОГДА не вычисляет время показа сам. Он умеет
 * ровно две вещи — оставить время, присланное сервером, или отказаться от него
 * и взять СЛЕДУЮЩУЮ присланную строку `at`. Собственная арифметика вида
 * «завтра в daily_time» стала бы вторым источником истины про окно и разошлась
 * бы с сервером ровно так же, как разошлись бы формулировки.
 */

/** Канал уведомлений Android. Заводится в localNotifications.js. */
export const CHANNEL_ID = 'aristea-events';

/**
 * Запас у ВЕРХНЕЙ границы окна, минуты. Решение владельца 13.09.2026.
 *
 * Зачем он есть. Точный будильник мы не запрашиваем (ни SCHEDULE_EXACT_ALARM,
 * ни USE_EXACT_ALARM — решение владельца: Google Play в планах, а там такое
 * разрешение пришлось бы обосновывать). Значит плагин ставит
 * `setAndAllowWhileIdle` — будильник НЕточный, и уведомление приезжает позже
 * назначенного. Приемлемым признан сдвиг 20–40 минут.
 *
 * ⚠️ Отсюда и величина: запас обязан покрывать тот сдвиг, который мы сами
 * считаем нормальным. Миримся с опозданием до 40 минут — значит ставить
 * ближе 40 минут к `push_quiet_from` означает сознательно целиться в тихие
 * часы: поставленное на 21:50 приедет в 22:30. 45 — это 40 с небольшим
 * резервом, потому что сама величина сдвига ничем не гарантирована.
 *
 * ⚠️ У НИЖНЕЙ границы запаса нет и не нужно: сдвиг работает только вперёд,
 * раньше срока неточный будильник не срабатывает никогда.
 */
export const QUIET_MARGIN_MINUTES = 45;

function parseHm(value, fallback) {
  const m = /^(\d{1,2}):(\d{2})$/.exec(String(value ?? '').trim());
  if (!m) return fallback;
  const h = Number(m[1]);
  const min = Number(m[2]);
  if (h > 23 || min > 59) return fallback;
  return [h, min];
}

const asMinutes = ([h, m]) => h * 60 + m;

/**
 * Часы и минуты момента в поясе, по которому сервер считал окно.
 *
 * Пояс сервер отдаёт в `timezone` ответа `/push/upcoming`. С 24.09.2026 это
 * пояс телефона (`tz` в запросе), пояс карты — только запасной. Сравнивать
 * всё равно по поясу ответа, а не по часам устройства: они расходятся, если
 * человек сменил пояс, а выдача ещё старая.
 */
export function hhmmInZone(date, timeZone) {
  try {
    const parts = new Intl.DateTimeFormat('en-GB', {
      timeZone, hour: '2-digit', minute: '2-digit', hour12: false,
    }).formatToParts(date);
    const get = (type) => Number(parts.find((p) => p.type === type)?.value);
    const h = get('hour');
    const m = get('minute');
    if (Number.isFinite(h) && Number.isFinite(m)) return [h % 24, m];
  } catch {
    /* неизвестный пояс — падаем на часы устройства, это честнее отказа */
  }
  return [date.getHours(), date.getMinutes()];
}

/**
 * Можно ли показывать в этот момент — окно сервера МИНУС запас сверху.
 *
 * Границы повторяют серверную `in_send_window` (backend/push/cron.py),
 * включая неочевидное: бессмысленная пара (верх не позже низа) означает «верхней
 * границы нет», а не пустое окно. Пустое окно тихо выключило бы уведомления
 * совсем, а снаружи это неотличимо от сломанного планировщика — поздний пуш
 * заметен и лечится, тишина нет.
 *
 * ⚠️ Из того же соображения сделан вырожденный случай ЗАПАСА: если всё окно
 * короче запаса (например `daily_time` 21:30 при `quiet_from` 22:00), запас не
 * применяется вовсе. Иначе в запас попали бы ВСЕ слоты разом, каждый переехал
 * бы на следующий — тоже в запас, и так до конца выдачи: получился бы не
 * перенос, а тихая потеря всех уведомлений.
 */
export function isAllowedMoment(date, win) {
  const start = asMinutes(parseHm(win?.dailyTime, [8, 0]));
  const end = asMinutes(parseHm(win?.quietFrom, [22, 0]));
  const now = asMinutes(hhmmInZone(date, win?.timeZone));

  if (now < start) return false;   // ниже нижней границы — запас тут не нужен
  if (end <= start) return true;   // бессмысленная пара: верхней границы нет
  const margin = (end - start) <= QUIET_MARGIN_MINUTES ? 0 : QUIET_MARGIN_MINUTES;
  return now < end - margin;
}

/**
 * Время показа, разрешённое с учётом запаса, для момента `iso`.
 *
 * Возвращает СТРОКУ: либо ту же самую, либо одну из `win.slots` — строк `at`,
 * присланных сервером. Своего времени не собирает никогда, и возвращает именно
 * исходную строку слота, а не пересобранную через `toISOString()`: склейка
 * событий одного дня опирается на совпадение `at` ДОСЛОВНО, и пересборка
 * развалила бы группу на два уведомления в одну минуту.
 *
 * `null` означает «разрешённого времени впереди нет» — вызывающий обязан
 * оставить событие на месте, а не выбросить его. Тихая потеря события здесь
 * стоила бы дороже позднего показа: именно на тихой потере уже один раз
 * сломался отбор транзитов.
 */
export function allowedAt(iso, win) {
  const t = Date.parse(iso);
  if (!Number.isFinite(t)) return null;
  // Нечем считать окно — не двигаем ничего. Догадываться о границах нельзя.
  if (!win || !win.quietFrom) return iso;
  if (isAllowedMoment(new Date(t), win)) return iso;

  const slots = (Array.isArray(win.slots) ? win.slots : [])
    .map((raw) => [Date.parse(raw), raw])
    .filter(([ms]) => Number.isFinite(ms))
    .sort((a, b) => a[0] - b[0]);

  for (const [ms, raw] of slots) {
    if (ms > t && isAllowedMoment(new Date(ms), win)) return raw;
  }
  return null;
}

/**
 * Сдвигает события, попавшие в запас, на следующий разрешённый слот.
 *
 * Применяется к СОБЫТИЯМ, а не к готовому плану, и это важно: сдвинутое
 * событие должно склеиться с теми, что уже стоят на этом слоте, а не приехать
 * отдельным уведомлением в ту же минуту. Склейка живёт в `buildPlan` и
 * работает по совпадению `at`, поэтому порядок только такой — сначала сдвиг,
 * потом склейка.
 *
 * `moved` и `late` возвращаются для диагностики (отладочная панель): `late` —
 * это те, кому переезжать некуда, они остались на месте и могут приехать позже
 * верхней границы.
 */
export function applyQuietMargin(events, win) {
  const out = [];
  let moved = 0;
  let late = 0;

  for (const e of Array.isArray(events) ? events : []) {
    if (!e || !e.at) { out.push(e); continue; }
    const next = allowedAt(e.at, win);
    if (next === null) { late += 1; out.push(e); continue; }
    if (next !== e.at) { moved += 1; out.push({ ...e, at: next }); continue; }
    out.push(e);
  }

  return { events: out, moved, late };
}

/**
 * Стабильный числовой id из строкового ключа `kind:ref`.
 *
 * Плагин принимает только целые (Java int), а ключ у нас строковый. Хэш
 * обязан быть УСТОЙЧИВЫМ между запусками: на этом держится и замена уже
 * поставленного уведомления вместо дубля, и адресная отмена — синхронизация
 * снимает ровно те id, которые сама же и ставила в прошлый раз.
 *
 * FNV-1a, срезанный до 31 бита: отрицательных id плагин не принимает.
 */
export function notificationId(key) {
  let h = 0x811c9dc5;
  for (let i = 0; i < key.length; i++) {
    h ^= key.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0) % 0x7fffffff;
}

/**
 * События одного дня склеиваются в ОДНО уведомление.
 *
 * Группируем по полю `at` дословно, а не по вычисленной из него дате: у ручки
 * `at` считается один раз на день окна (начало окна отправки в этот день),
 * поэтому совпадение строки `at` и есть «один день» по построению. Своей
 * арифметики над датами и часовыми поясами клиенту при этом не нужно вовсе —
 * а значит нечему и разойтись с серверной.
 *
 * Порядок событий внутри дня — серверный, как пришёл. Переставлять нельзя:
 * ручка отдаёт их в порядке отбора, и своя сортировка была бы собственным
 * суждением о важности, то есть вторым критерием отбора.
 */
export function buildPlan(events, nowMs = Date.now()) {
  const groups = new Map();
  const seen = new Set();

  for (const e of Array.isArray(events) ? events : []) {
    if (!e || !e.key || !e.at || !e.title) continue;

    // Дедуп по `key` = `kind:ref` — ровно тому, по которому дедуплицирует
    // сервер (уникальный индекс user_id, kind, ref_key). Ключ собран из
    // события, а не из даты запроса, и переживает правку формулировок.
    // Ручка дедуплицирует и сама, но проверка стоит и здесь: цена — строка,
    // а цена пропуска — два одинаковых уведомления в одной шторке.
    if (seen.has(e.key)) continue;
    seen.add(e.key);

    const at = Date.parse(e.at);
    // Прошедшее не планируют. Ручка это уже отсекает по своему «сейчас», но
    // между её ответом и этим кодом проходит время, а на устройстве ещё и
    // свои часы: событие может успеть протухнуть.
    if (!Number.isFinite(at) || at <= nowMs) continue;

    if (!groups.has(e.at)) groups.set(e.at, []);
    groups.get(e.at).push(e);
  }

  const plan = [];
  for (const [at, items] of groups) {
    const first = items[0];
    const rest = items.slice(1);
    plan.push({
      id: notificationId(first.key),
      keys: items.map((i) => i.key),
      at,
      title: first.title,
      // Одно событие — текст сервера дословно. Несколько — тот же текст плюс
      // заголовки остальных списком: ни одного своего слова, только
      // разделители.
      body: rest.length ? `${first.body}\n${rest.map((i) => i.title).join(' · ')}` : first.body,
      url: first.url,
      // Куда вести в приложении по нажатию (notificationTap.js). В склейке —
      // первый найденный: сегодня target есть только у ежедневного прогноза.
      target: (items.find((i) => i.target) || {}).target || null,
    });
  }

  plan.sort((a, b) => Date.parse(a.at) - Date.parse(b.at));
  return plan;
}
