/**
 * plannerAccess.js — что сказать человеку про ЗАКРЫТОЕ событие планера.
 *
 * ⚠️ Правило вынесено отдельным файлом по той же причине, что channelChoice.js:
 * внутри панели его нечем закрепить, кроме глаз, а ошибка тут — обещание
 * ЧУЖОГО тарифа. Ровно этот класс дефекта уже ловили дважды: приписка к
 * интерпретации звала free через тариф (CLAUDE.md, «Приписка зовёт в соседний
 * тариф») и письма обещали 5 PDF при флаге 15.
 *
 * ⚠️ Главное, что здесь неочевидно: `locked` больше НЕ означает «купи тариф».
 * С 16.09.2026 у проходов Луны по домам закрытое будущее есть и у платных —
 * расшифровка идёт на четыре недели вперёд у ВСЕХ платных тарифов. Значит для
 * Веги, Лиры и Ориона закрытый проход это ГОРИЗОНТ, а не витрина: покупать
 * нечего, оно откроется само по мере приближения срока. Показать там «открыть
 * доступ» значило бы продать человеку то, что у него уже куплено.
 *
 * Поэтому решение принимается по паре (тариф, вид события), а не по одному
 * флагу `locked`:
 *
 *   planner_moon_house  — гейт тарифа только на free (у платных 4 недели);
 *   planner_period      — гейт тарифа только на free (is_month_period_locked);
 *   planner_longterm    — гейт тарифа на free И на Веге (is_longterm_locked:
 *                         открыто с Лиры).
 *
 * Источник этих трёх правил — `backend/transit/planner_engine.py`. Здесь их
 * ВТОРАЯ копия, и она обязана совпадать: разъедется — человек увидит кнопку,
 * которая ничего ему не даст, или не увидит той, которая дала бы.
 * Закреплено plannerAccess.test.js.
 */

/** Тарифы, на которых долгосрочные периоды открыты (см. is_longterm_locked). */
const LONGTERM_TIERS = ['pro', 'premium'];

/**
 * Открывает ли переход на старший тариф это конкретное закрытое событие.
 *
 * `known === false` (тариф ещё не приехал) трактуется как «не продавать»:
 * показать заплатившему предложение купить хуже, чем не показать его
 * бесплатному — второе он увидит на витрине и без нас.
 */
export function upgradeOpensIt(event, tier, known = true) {
  if (!event?.locked || !known) return false;
  if (tier === 'free') return true;
  if (event.kind === 'planner_longterm') return !LONGTERM_TIERS.includes(tier);
  return false;
}

/**
 * Строка под каркасом закрытого события планера.
 *
 * ⚠️ Числа («четыре недели») здесь намеренно НЕ подставляются из
 * PLANNER_WEEKS_AHEAD: эта строка про горизонт вообще, а не про тариф, и
 * привязка к числу заставила бы её меняться вместе с сеткой там, где меняться
 * нечему. Витрина с числом живёт в constants.js, и она одна.
 */
export function lockedPlannerText(event, tier, known = true) {
  if (upgradeOpensIt(event, tier, known)) {
    return event?.kind === 'planner_longterm'
      ? 'Долгосрочные периоды с разбором открываются на старшем тарифе.'
      : 'Рекомендации на этот период открываются на платном тарифе. Прошедшие периоды и текущая неделя открыты всегда.';
  }
  return 'Рекомендации появятся ближе к сроку — планер открыт на четыре недели вперёд.';
}
