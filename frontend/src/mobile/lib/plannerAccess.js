/** Тарифы, на которых долгосрочные периоды открыты (см. is_longterm_locked). */
const LONGTERM_TIERS = ['pro', 'premium'];

/**
 * Открывает ли переход на старший тариф это конкретное закрытое событие.
 *
 * `known === false` (тариф ещё не приехал) трактуется как «не продавать»:
 * показать заплатившему предложение купить хуже, чем не показать его
 * бесплатному — второе он увидит на витрине и без нас.
 */
export function upgradeOpensIt(event, tier, known = true) {
  if (!event?.locked || !known) return false;
  if (tier === 'free') return true;
  if (event.kind === 'planner_longterm') return !LONGTERM_TIERS.includes(tier);
  // Платному закрытых проходов Луны и месячных периодов не бывает. Если такое
  // событие всё же пришло — сервер и клиент разошлись по тарифной сетке, и
  // продавать наугад хуже, чем промолчать.
  return false;
}

/**
 * Строка под каркасом закрытого события планера.
 *
 * ⚠️ Числа («четыре недели») здесь намеренно НЕ подставляются из
 * PLANNER_WEEKS_AHEAD: эта строка про горизонт вообще, а не про тариф, и
 * привязка к числу заставила бы её меняться вместе с сеткой там, где меняться
 * нечему. Витрина с числом живёт в constants.js, и она одна.
 */
export function lockedPlannerText(event, tier, known = true) {
  if (upgradeOpensIt(event, tier, known)) {
    return event?.kind === 'planner_longterm'
      ? 'Долгосрочные периоды с разбором открываются на старшем тарифе.'
      : 'Рекомендации на этот период открываются на платном тарифе. Прошедшие периоды и текущая неделя открыты всегда.';
  }
  // ⚠️ Пусто, а не общая фраза. Сюда попадает только расхождение сетки между
  // сервером и клиентом (см. upgradeOpensIt): сказать «откроется на платном»
  // заплатившему — обещание чужого тарифа, а придумывать третью формулировку
  // под состояние, которого не должно существовать, значит закреплять его.
  return '';
}
