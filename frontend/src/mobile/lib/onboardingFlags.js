/**
 * onboardingFlags.js — «видел / не видел» для приветствия и подсказок
 * (SPEC_ONBOARDING.md §6, §7).
 *
 * Отдельно от onboardingCopy.js намеренно: там данные текстов, здесь —
 * работа с хранилищем. Общего у них только слово «онбординг».
 *
 * ⚠️ `localStorage` может быть НЕДОСТУПЕН (приватный режим, ограничения
 * webview, отключённое хранилище) — обращение к нему тогда БРОСАЕТ
 * исключение, а не возвращает null. Поэтому и чтение, и запись обёрнуты в
 * try/catch: при отказе считаем «не видел», работаем дальше, интерфейс не
 * блокируем и ошибку человеку не показываем. Канонический образец того же
 * приёма в проекте — useTheme.jsx; второй способ не заводим, повторяем этот.
 *
 * Практическое следствие отказа хранилища, принятое сознательно: приветствие
 * показывается один раз ЗА ЗАПУСК, а не один раз навсегда — записать
 * «видел» некуда. Внутри одной сессии повтора нет, за это отвечает
 * `memory` ниже: хранилище отвечает на вопрос «показывать ли при следующем
 * запуске», память — «показывать ли прямо сейчас».
 */

export const WELCOME_KEY = 'aristea.onboarding.seen';
export const HINTS_KEYS = {
  chart: 'aristea.hints.chart.seen',
  feed: 'aristea.hints.feed.seen',
};

/** Значение флага. Проверка идёт на равенство именно ему, а не на
 * truthiness: любое другое содержимое ключа (мусор, старый формат) значит
 * «не видел» — человек увидит подсказку лишний раз вместо того, чтобы не
 * увидеть её никогда. */
const SEEN = '1';

// Дубль флагов в памяти процесса. Нужен ровно для случая недоступного
// хранилища (см. шапку): без него приветствие показывалось бы заново на
// каждом перемонтировании в рамках одного запуска.
const memory = new Set();

export function isSeen(key) {
  if (memory.has(key)) return true;
  try {
    return localStorage.getItem(key) === SEEN;
  } catch {
    // Хранилище недоступно — считаем «не видел». Не падаем.
    return false;
  }
}

/**
 * Пометить как увиденное.
 *
 * ⚠️ Вызывать ТОЛЬКО по завершении или по явному отказу («Пропустить»,
 * «Понятно» на последнем шаге). Не при показе и не после первого шага:
 * человек, закрывший приложение на середине, обязан увидеть онбординг
 * снова, с начала (SPEC_ONBOARDING.md §6). Выбор в пользу «показать лишний
 * раз» вместо «потерять единственный показ» — второе необратимо.
 */
export function markSeen(key) {
  memory.add(key);
  try {
    localStorage.setItem(key, SEEN);
  } catch {
    // Потеря персиста не должна ронять переход по кнопке: в рамках сессии
    // флаг уже в memory, при следующем запуске онбординг просто повторится.
  }
}
