import { fetchSubscription } from './moreApi';

let cached = null;      // последний успешный ответ /profile/subscription
let inFlight = null;    // промис незавершённого запроса — для дедупликации
const listeners = new Set();

function publish() {
  for (const fn of listeners) fn(cached);
}

/**
 * Подписка. Возвращает функцию отписки.
 * Если ответ уже есть, слушатель получает его сразу — иначе экран, смонтированный
 * после завершения запроса, ждал бы следующего обновления вечно.
 */
export function onSubscription(fn) {
  listeners.add(fn);
  if (cached) fn(cached);
  return () => listeners.delete(fn);
}

/**
 * Свежая подписка. Повторные вызовы, пока запрос идёт, отдают ТОТ ЖЕ промис.
 *
 * @param {{force?: boolean}} [opts] — `force` игнорирует кэш (жест обновления
 *        на «Ещё»: человек тянет экран именно чтобы увидеть новое).
 */
export function getSubscription({ force = false } = {}) {
  if (!force && cached) return Promise.resolve(cached);
  if (inFlight) return inFlight;

  inFlight = fetchSubscription()
    .then((data) => {
      cached = data;
      publish();
      return data;
    })
    .finally(() => { inFlight = null; });

  return inFlight;
}

/** Последний известный ответ или null. Синхронно, без запроса. */
export function peekSubscription() {
  return cached;
}

/** Забыть всё — вызывается при выходе из аккаунта: тариф чужой. */
export function resetSubscription() {
  cached = null;
  inFlight = null;
  publish();
}
