/**
 * shareRules.js — правила листа «Поделиться картой». Чистые функции без
 * импортов, как chartCreateRules.js рядом: DOM-окружения для тестов в
 * проекте нет, и всё, что можно проверить, обязано жить вне компонента.
 *
 * ⚠️ Здесь проверяется НЕ вёрстка, а один инвариант приватности: действие
 * (создание публичной ссылки) не может выполниться раньше, чем человек
 * увидел, ЧТО вместе с этой ссылкой уходит. Формально —
 * `mayRunShareAction(step)` обязан быть подмножеством
 * `disclosureVisible(step)`. Если однажды кто-то добавит быструю кнопку
 * «поделиться» мимо листа, инвариант сломается на тесте, а не у человека,
 * который уже отправил свою дату и место рождения в чат.
 *
 * Почему предупреждение вообще нужно, и почему его текст именно такой —
 * разведка по бэкенду 08.09.2026:
 *   · `GET /api/v1/share/{token}/data` (`backend/share_router.py:231-249`)
 *     отдаёт `birth_date`, `birth_place`, полные `planets`/`houses`/
 *     `aspects`/`ascendant`/`midheaven` — то есть по ссылке видно и дату, и
 *     место рождения, а не только знаки Солнца/Луны/Асцендента;
 *   · то же самое напечатано прямо на картинке (`share_router.py:621-623`);
 *   · срок — 90 дней (`SHARE_TTL_SECONDS`, `share_router.py:41`);
 *   · ⚠️ ОТЗЫВА НЕТ: эндпоинта, гасящего `public_token`, в бэкенде не
 *     существует вовсе. Единственный способ убить ссылку — удалить карту
 *     («Ещё» → «Мои карты»).
 * Реальное имя (`chart.name`) по ссылке НЕ уходит — карточка подписана
 * `share_name`, а его сегодня не задаёт ни один вызывающий; поэтому в
 * тексте про имя не говорим ни «уходит», ни «не уходит»: обещание про
 * чужое поле пришлось бы сопровождать бэкенд.
 *
 * ⚠️ Системного листа Android здесь нет и он не «забыт»: `navigator.share`
 * в Android WebView отсутствует (caniuse `web-share`, строка `android` —
 * `n`, при `and_chr: y`; проверено по локальному caniuse-lite 08.09.2026).
 * Дело не в `androidScheme`/origin `https://localhost` — secure context
 * выполнен, API просто нет: Web Share требует, чтобы его реализовало
 * хост-приложение, а Capacitor этого не делает. Настоящий системный лист
 * дал бы только плагин `@capacitor/share` — новая нативная зависимость и
 * пересборка проекта. Не ставим по существу: обе кнопки листа закрыты тем,
 * что в приложении уже есть (`navigator.clipboard` и `openInBrowser`), и
 * плагин не дал бы ни одной возможности сверх этого. Счёт плагинов тут ни
 * при чём — правило «один плагин на приложение» отменено 10.09.2026.
 * Если плагин когда-нибудь поставят — переводить на системный лист надо ОБА
 * места сразу (здесь и `MoreReferralView.jsx`): два разных способа
 * поделиться ссылкой в одном приложении — дефект сам по себе.
 */

/** Срок жизни ссылки. Дублирует `SHARE_TTL_SECONDS` бэкенда осознанно:
 *  число нужно в тексте предупреждения, а с сервера оно не приходит ничем.
 *  Разойдётся — предупреждение станет неправдой; проверять глазами при
 *  правке `share_router.py:41`. */
export const SHARE_TTL_DAYS = 90;

/** Текст предупреждения. Одной строкой на пункт — так же читается в листе. */
export const SHARE_DISCLOSURE = Object.freeze([
  'По ссылке видны дата и место рождения — не только знаки.',
  `Ссылка работает ${SHARE_TTL_DAYS} дней и отозвать её нельзя: закрыть доступ можно, только удалив карту.`,
]);

/** Шаги листа. 'closed' — листа нет на экране. */
export const SHARE_STEPS = Object.freeze({
  CLOSED: 'closed',
  DISCLOSURE: 'disclosure',
  WORKING: 'working',
  ERROR: 'error',
});

/** Предупреждение на экране — во всех шагах, кроме закрытого. */
export function disclosureVisible(step) {
  return step !== SHARE_STEPS.CLOSED;
}

/**
 * Можно ли прямо сейчас запускать действие (создание ссылки).
 *
 * 'working' исключён не ради инварианта, а чтобы второй тап не создал
 * второй запрос; 'closed' — ради самого инварианта.
 */
export function mayRunShareAction(step) {
  return step === SHARE_STEPS.DISCLOSURE || step === SHARE_STEPS.ERROR;
}
