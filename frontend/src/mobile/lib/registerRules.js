/**
 * registerRules.js — правила формы регистрации на клиенте: проверка полей до
 * запроса и разбор ответов обеих OTP-ручек.
 *
 * Вынесено из экрана намеренно: это единственная часть регистрации, которую
 * можно проверить тестами без устройства и без живых запросов к боевым ручкам
 * (любой такой запрос создаёт настоящий аккаунт и шлёт настоящее письмо).
 * Экран остаётся вёрсткой и переходами между шагами.
 *
 * Полный контракт ручек — REGISTER_API_RECON.md.
 */

/**
 * Почтовые домены, которые принимает бэкенд (`RU_EMAIL_DOMAINS`,
 * `backend/schemas.py`). Показываются человеку ПОДСКАЗКОЙ под полем ввода:
 * ограничение жёсткое и до отправки формы неочевидное — без подсказки первый
 * же gmail-адрес получает 422 после заполнения всей формы.
 *
 * ⚠️ Это КОПИЯ серверного списка, второй источник истины. Осознанно: правка
 * бэкенда в эту задачу не входила (решение владельца 07.09.2026), а показать
 * список надо. Поэтому копия используется ТОЛЬКО как текст подсказки и
 * НИКОГДА для валидации — домен проверяет сервер. Если список на бэкенде
 * пополнится, подсказка станет неполной, но регистрация с новым доменом
 * продолжит работать. Наоборот (клиент отбивает то, что сервер принимает) не
 * случится, потому что здесь нет проверки.
 */
export const RU_EMAIL_DOMAINS_HINT = [
  'yandex.ru', 'ya.ru',
  'mail.ru', 'bk.ru', 'list.ru', 'inbox.ru', 'internet.ru',
  'rambler.ru', 'lenta.ru', 'autorambler.ru', 'myrambler.ru', 'ro.ru',
];

/**
 * Проверка формы до запроса — повторяет веб (`AuthModal.jsx`,
 * `handleSendCode`), включая то, чего он НЕ делает: домен здесь не
 * проверяется, только наличие «@». Иначе клиент начал бы отбивать адреса,
 * которые сервер принимает.
 *
 * Возвращает текст первой ошибки или null. Порядок проверок тот же, что на
 * вебе: человек, привыкший к сайту, увидит те же подсказки в том же порядке.
 */
export function validateRegisterForm({ email, password, password2, consent }) {
  if (!email || !password) return 'Заполни все поля';
  if (!email.includes('@')) return 'Введи корректный email';
  if (password.length < 8) return 'Пароль минимум 8 символов';
  if (/^\d+$/.test(password)) return 'Пароль не может состоять только из цифр';
  if (password !== password2) return 'Пароли не совпадают';
  if (!consent) return 'Нужно подтвердить согласие на обработку персональных данных';
  return null;
}

/** Код — ровно шесть цифр (`VerifyEmailOTPRequest`, pattern `^\d{6}$`). */
export function validateOtpCode(code) {
  return /^\d{6}$/.test(code) ? null : 'Введи 6-значный код';
}

/** Оставляет только цифры и не длиннее шести — для поля ввода кода. */
export function normalizeOtpInput(value) {
  return String(value ?? '').replace(/\D/g, '').slice(0, 6);
}

// ── Разбор ответов ────────────────────────────────────────────────────────

/**
 * Начало текста нашего троттла на повторную отправку (`register_email_send`,
 * `backend/auth/router.py`). По нему один вид 429 отличается от другого.
 *
 * ⚠️ «Подожди», а не «Подожди минуту»: с 24.09.2026 сервер на «ты»
 * («Подожди минуту…»), а сервер прошлой недели отвечал «Подождите минуту…».
 * «Подожди» — общее начало обеих форм, так новый APK узнаёт троттл от
 * любого сервера. Старые APK держат «Подождите минуту» и на новом сервере
 * покажут текст лимита по IP вместо «повторить через минуту» — это цена
 * перевода, другого пути у уже установленных сборок нет.
 */
const RESEND_THROTTLE_MARK = 'Подожди';

const IP_LIMIT_TEXT = 'Слишком много запросов кода с этого адреса. '
  + 'Попробуй через час или войди, если аккаунт уже есть.';

const RESEND_THROTTLE_TEXT = 'Код уже отправлен. Повторить можно через минуту.';

/**
 * Разбирает ошибку шага 1 (`send-code`).
 *
 * ⚠️ Два РАЗНЫХ 429, и путать их нельзя (REGISTER_API_RECON.md §2):
 *
 *   • наш троттл — минута, ключ по АДРЕСУ, тело `{"detail": "Подождите
 *     минуту перед повторной отправкой."}`;
 *   • лимитер slowapi — 5 в час, ключ по IP, тело другой формы (`error`,
 *     а не `detail`), поэтому apiFetch кладёт в сообщение statusText.
 *
 * Различаем по НАШЕЙ строке в detail, а не по форме ответа лимитера: наша
 * строка — наш же код, она стабильна и проверяема, а формат slowapi может
 * измениться с версией пакета, и тогда молча сломалось бы различение.
 *
 * Разница видна человеку: минуту ждут, час — нет. За общим NAT оператора или
 * в публичном Wi-Fi лимит по IP делится на всех, кто за тем же адресом, —
 * то есть «подождите минуту» там было бы прямой ложью.
 *
 * @returns {{ text: string, kind: 'resend'|'ip-limit'|'validation'|'unknown' }}
 */
export function describeSendCodeError(err) {
  const status = err?.status;
  const detail = typeof err?.detail?.detail === 'string' ? err.detail.detail : '';
  const message = typeof err?.message === 'string' ? err.message : '';

  if (status === 429) {
    const ours = detail.includes(RESEND_THROTTLE_MARK) || message.includes(RESEND_THROTTLE_MARK);
    return ours
      ? { text: RESEND_THROTTLE_TEXT, kind: 'resend' }
      : { text: IP_LIMIT_TEXT, kind: 'ip-limit' };
  }

  // 422 — pydantic: домен не из списка, слабый пароль, нет согласия.
  // apiFetch уже склеил список ошибок и срезал префикс «Value error, ».
  if (status === 422) {
    return { text: message || 'Проверь правильность заполнения полей.', kind: 'validation' };
  }

  return { text: message || 'Не удалось отправить код. Попробуй ещё раз.', kind: 'unknown' };
}

/** Признак того, что код больше не действует и нужен новый. */
const EXPIRED_MARKS = ['Код устарел', 'Превышено число попыток'];

/**
 * Разбирает ошибку шага 2 (`verify`).
 *
 * У 400 три разных текста, и для человека они значат разное:
 *
 *   • «Неверный код. Осталось попыток: N.» — можно вводить дальше;
 *   • «Код устарел. Запросите новый.» — вводить нечего, нужен новый код;
 *   • «Превышено число попыток. Запросите новый код.» — то же самое, запись
 *     при этом уже удалена сервером, поэтому следующий запрос ответит
 *     «Код устарел» (два разных текста об одном состоянии).
 *
 * ⚠️ `offerLogin` — не украшение. Успешная проверка кода УДАЛЯЕТ запись, и
 * аккаунт к этому моменту уже создан. Если ответ 201 не доехал (обрыв сети в
 * момент ответа), повтор даст ровно «Код устарел» — при том, что аккаунт
 * существует и войти в него можно паролем, который человек только что
 * придумал. Без подсказки он останется в тупике: повторная отправка кода
 * ответит 200 и пришлёт письмо «аккаунт уже существует», а не код (решение
 * владельца 07.09.2026, REGISTER_API_RECON.md §6 п. 3).
 *
 * @returns {{ text: string, kind: 'wrong-code'|'expired'|'exists'|'validation'|'unknown',
 *             offerLogin: boolean }}
 */
export function describeVerifyError(err) {
  const status = err?.status;
  const detail = typeof err?.detail?.detail === 'string' ? err.detail.detail : '';
  const message = typeof err?.message === 'string' ? err.message : '';
  const text = detail || message;

  if (status === 409) {
    // Аккаунт успели создать между шагами — войти по паролю можно прямо сейчас.
    return { text: text || 'Аккаунт с таким email уже существует.', kind: 'exists', offerLogin: true };
  }

  if (status === 400) {
    const expired = EXPIRED_MARKS.some((mark) => text.includes(mark));
    if (expired) {
      return { text, kind: 'expired', offerLogin: true };
    }
    return { text, kind: 'wrong-code', offerLogin: false };
  }

  if (status === 422) {
    return { text: message || 'Код должен состоять из шести цифр.', kind: 'validation', offerLogin: false };
  }

  return {
    text: message || 'Не удалось подтвердить код. Попробуй ещё раз.',
    kind: 'unknown',
    offerLogin: false,
  };
}
