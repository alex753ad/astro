/**
 * localNotificationsSync.js — когда приложение перепланирует локальные
 * уведомления и при каких условиях.
 *
 * Разделение с соседними файлами: `localNotificationPlan.js` считает ЧТО
 * показать и КОГДА (чистая логика, покрыта тестами), `localNotifications.js`
 * умеет поставить это на устройстве, а здесь — ТОЛЬКО условия и момент.
 *
 * ⚠️ Почему перепланирование вообще нужно, а не «поставили один раз».
 * Локальное уведомление живёт в системе, а не в приложении, и расходится с
 * реальностью само собой: транзит пересчитан, человек поменял основную карту,
 * выключил вид уведомлений в настройках, окно выдачи (7 дней) просто
 * закончилось. Поэтому план пересобирается при каждом заходе в приложение и
 * при каждом возврате из фона — это и есть единственный момент, когда
 * приложение вообще выполняется.
 *
 * ⚠️ Пересборка трогает ровно СВОЁ множество (`scheduleFromUpcoming`), а не
 * всё, что вернул `getPending`. До 13.09.2026 было наоборот, и это съедало
 * чужие записи — в первую очередь проверочное уведомление из отладочной
 * панели, которое исчезало при первом же возврате в приложение.
 *
 * ⚠️ Перезагрузка телефона — отдельный случай, и его закрывает НЕ этот файл.
 * Планировщик Android (AlarmManager) теряет все будильники при перезагрузке.
 * Плагин это знает: он хранит поставленные уведомления у себя и восстанавливает
 * их в `LocalNotificationRestoreReceiver` по BOOT_COMPLETED (разрешение
 * RECEIVE_BOOT_COMPLETED приезжает из манифеста самого плагина). Проверено
 * чтением его исходника в node_modules 13.09.2026.
 *
 * Из того же исходника — две вещи, которые надо знать заранее:
 *   • уведомление, чьё время прошло, пока телефон был выключен, получает новое
 *     время «сейчас + 15 секунд». То есть после включения телефона ночью
 *     пропущенное утреннее уведомление придёт сразу — мимо тихих часов.
 *     Средствами плагина это не выключается; чинится только нативным кодом
 *     или отказом от восстановления вовсе, и ни то ни другое сегодня не
 *     оправдано: за ночь такого не накапливается больше одного.
 *   • доставленное уведомление плагин из своего хранилища удаляет, поэтому
 *     восстановление не воскрешает уже показанное.
 * Следом за восстановлением всё равно приходит эта синхронизация — при первом
 * же открытии приложения план пересобирается по свежей выдаче.
 */

import { fetchPushSettings, fetchUpcomingNotifications } from './moreApi';
import {
  LOCAL_NOTIFICATIONS_SUPPORTED,
  cancelOwnedPlan,
  permissionState,
  scheduleFromUpcoming,
} from './localNotifications';

/**
 * Намерение человека, отдельно от системного разрешения.
 *
 * Разрешение отвечает на вопрос «можно ли», тумблер — «хочет ли». Их нельзя
 * смешивать: разрешение выдаётся один раз и навсегда, а выключить уведомления
 * человек должен уметь, не отзывая его в настройках Android.
 */
const ENABLED_KEY = 'aristea_local_notifications';

export function localNotificationsEnabled() {
  try {
    return localStorage.getItem(ENABLED_KEY) === '1';
  } catch {
    return false;
  }
}

export function setLocalNotificationsEnabled(on) {
  try {
    localStorage.setItem(ENABLED_KEY, on ? '1' : '0');
  } catch {
    /* приватный режим webview — тумблер просто не запомнится */
  }
}

/**
 * Границы окна и список разрешённых слотов — всё, что нужно запасу у верхней
 * границы (`applyQuietMargin`).
 *
 * ⚠️ `slots` — это строки `at` из выдачи, а не вычисленные времена. Клиент,
 * отказавшись от слота, обязан взять другой ПРИСЛАННЫЙ, а не собрать свой:
 * собственная арифметика окна стала бы вторым источником истины и разошлась бы
 * с сервером ровно так же, как разошлись бы формулировки.
 */
export function windowFrom(upcoming, settings) {
  const seen = [];
  for (const e of upcoming?.events || []) {
    if (e?.at && !seen.includes(e.at)) seen.push(e.at);
  }
  return {
    dailyTime: settings?.daily_time || '08:00',
    quietFrom: settings?.quiet_from || '22:00',
    timeZone: upcoming?.timezone || 'Europe/Moscow',
    slots: seen,
  };
}

/**
 * Пересобрать план. Возвращает число поставленных уведомлений.
 *
 * Тихо выходит во всех трёх случаях «нельзя»: не мобильное приложение, тумблер
 * выключен, разрешения нет. Ни один из них не ошибка и ни один не повод
 * спрашивать разрешение — спрашивают только по тапу на тумблер
 * (MoreNotificationsView), см. CLAUDE.md про выраженное намерение.
 */
export async function syncLocalNotifications() {
  if (!LOCAL_NOTIFICATIONS_SUPPORTED) return 0;

  if (!localNotificationsEnabled()) {
    // Выключенный тумблер обязан снимать уже поставленный ПЛАН: иначе
    // уведомления продолжат приходить ещё неделю после выключения — по плану,
    // который лежит в системе, а не в приложении.
    await cancelOwnedPlan();
    return 0;
  }

  if ((await permissionState()) !== 'granted') return 0;

  try {
    // Два запроса, а не один: границы окна живут в /push/settings, а слоты и
    // пояс — в /push/upcoming. Параллельно, они друг от друга не зависят.
    const [upcoming, settings] = await Promise.all([
      fetchUpcomingNotifications(),
      fetchPushSettings(),
    ]);
    return await scheduleFromUpcoming(
      upcoming?.events || [],
      Date.now(),
      windowFrom(upcoming, settings),
    );
  } catch (err) {
    // Нет сети — оставляем уже поставленное как есть. Снести план из-за
    // неудачного запроса значило бы лишить человека уведомлений ровно тогда,
    // когда приложение и так не работает.
    // eslint-disable-next-line no-console
    console.warn('[push] не удалось обновить план уведомлений:', err);
    return 0;
  }
}
