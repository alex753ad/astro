/**
 * channelChoice.js — какой канал уведомлений работает на этом устройстве.
 *
 * Каналов два, и они решают одну задачу разными средствами:
 *   • `server` — пуш через FCM. Будит устройство, но требует сервисов Google.
 *   • `device` — локальные уведомления. Работают везде, но НЕ будят телефон:
 *     без разрешения на точный будильник Android ставит неточный, и тот ждёт,
 *     пока человек сам возьмёт телефон (docs/HISTORY-push.md).
 *
 * ⚠️ ФАЙЛ СУЩЕСТВУЕТ РАДИ ОДНОГО ИНВАРИАНТА: активен ровно один канал.
 * Оба сразу означают, что одно и то же событие придёт дважды — пушем и
 * локальным уведомлением о том же самом. Правило само по себе на три строки, и
 * соблазн написать его прямо в обработчике тумблера велик; вынесено оно потому,
 * что внутри компонента этот инвариант нечем закрепить, кроме рендера, а
 * стоимость его нарушения — дубли в шторке у каждого, кто включил уведомления.
 *
 * Здесь только РЕШЕНИЕ. Последствия (снять план, зарегистрировать токен)
 * применяет вызывающий: так решение остаётся чистой функцией и проверяется
 * перебором всех случаев, а не сценарием на устройстве.
 */

/** Пуш через FCM: работает и будит устройство. */
export const CHANNEL_SERVER = 'server';
/** Локальные уведомления: запасной канал, телефон не будит. */
export const CHANNEL_DEVICE = 'device';

/**
 * @param {string|null} token      токен FCM, если регистрация удалась
 * @param {string} permission      состояние системного разрешения
 * @returns {'server'|'device'|null}
 *
 * ⚠️ Порядок проверок не взаимозаменяем. Серверный канал будит устройство,
 * локальный нет — выбрать локальный там, где работает серверный, значит
 * сознательно отдать человеку худший канал. Поэтому токен проверяется первым.
 *
 * ⚠️ Токен без разрешения — не противоречие, а нормальный случай: разрешение
 * могли отозвать в настройках телефона уже после регистрации. Сервер об этом не
 * знает и продолжит слать, поэтому канал остаётся серверным: показывать или нет
 * — решает система, а наше дело не отнять у неё эту возможность, подсунув
 * локальные, которые без разрешения тем более не покажутся.
 */
export function decideChannel(token, permission) {
  if (token) return CHANNEL_SERVER;
  if (permission === 'granted') return CHANNEL_DEVICE;
  return null;
}

/**
 * Что должно быть включено при выбранном канале.
 *
 * Возвращает пару флагов, а не команды: вызывающий сам решает, как их
 * применить. Нужна она затем, чтобы инвариант «ровно один» проверялся на
 * ФЛАГАХ — то есть на том, что реально включено, — а не на названии канала.
 */
export function channelState(channel) {
  return {
    serverPush: channel === CHANNEL_SERVER,
    localNotifications: channel === CHANNEL_DEVICE,
  };
}
