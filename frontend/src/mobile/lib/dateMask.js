/**
 * dateMask.js — дата рождения вводится текстом «ДД.ММ.ГГГГ», а не системным
 * пикером.
 *
 * ⚠️ Почему отказались от `input type="date"`, хотя он дал бы нативный
 * диалог бесплатно: в календаре Android год выбирается прокруткой, и для
 * даты рождения это самый длинный путь из возможных — до 1996 года крутить
 * тридцать лет. Дата рождения вводится один раз и известна человеку
 * наизусть; четыре касания клавиатуры быстрее любого календаря. У ВРЕМЕНИ
 * этой беды нет (циферблат отдаёт ЧЧ:ММ за два касания), поэтому
 * `input type="time"` остаётся нативным — решение владельца 08.09.2026, и
 * это не непоследовательность, а разная цена одного и того же жеста.
 *
 * Логика та же, что на вебе (`DateMaskInput`, `components/BirthForm.jsx`), но
 * переписана функциями без React: тот файл общий с вебом, править его ради
 * мобильного экрана нельзя, а внутри компонента эти правила нечем покрыть
 * тестами — DOM-окружения в проекте нет.
 */

/** «1996-05-28» → «28.05.1996». Пустое и неполное — пустая строка. */
export function isoToDisplay(iso) {
  if (!iso) return '';
  const [y, m, d] = String(iso).split('-');
  if (!y || !m || !d) return '';
  return `${d}.${m}.${y}`;
}

/**
 * «28.05.1996» → «1996-05-28». Неполный ввод даёт пустую строку, а не
 * половину даты: недособранное значение не должно доехать ни до проверок
 * формы, ни тем более до запроса.
 */
export function displayToIso(display) {
  const digits = onlyDigits(display);
  if (digits.length !== 8) return '';
  return `${digits.slice(4, 8)}-${digits.slice(2, 4)}-${digits.slice(0, 2)}`;
}

/** Всё, кроме цифр, выбрасывается — включая буквы, вставленные из буфера. */
function onlyDigits(value) {
  return String(value ?? '').replace(/\D/g, '');
}

/**
 * Ввод человека → то, что показывается в поле.
 *
 * Точки расставляются сами и в поле не набираются: клавиатура открыта
 * цифровая (`inputMode="numeric"`), точки на ней может не быть вовсе.
 * Лишние цифры за пределами восьми отбрасываются — иначе «28.05.19966»
 * молча превратилось бы в другой год.
 */
export function maskDateInput(value) {
  const digits = onlyDigits(value).slice(0, 8);
  if (digits.length > 4) return `${digits.slice(0, 2)}.${digits.slice(2, 4)}.${digits.slice(4)}`;
  if (digits.length > 2) return `${digits.slice(0, 2)}.${digits.slice(2)}`;
  return digits;
}

/**
 * Введено ли хоть что-нибудь. Нужно, чтобы отличить «поле не трогали» от
 * «дата набрана наполовину»: у этих двух случаев разный текст ошибки, а
 * `displayToIso` возвращает для обоих пустую строку (§4 SPEC_CHART_CREATE.md).
 */
export function hasDigits(display) {
  return onlyDigits(display).length > 0;
}
