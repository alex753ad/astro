/**
 * interpretRules.js — правила экрана разбора: чем кончился поток и надо ли
 * перезапрашивать при возврате из фона (SPEC_INTERPRETATION.md §6, §7).
 *
 * Чистые функции без импортов, как chartCreateRules.js и shareRules.js рядом:
 * DOM-окружения для тестов в проекте нет, и всё, что можно проверить, обязано
 * жить вне компонента.
 *
 * ⚠️ Главное, ради чего этот файл существует: отказ по лимиту приезжает
 * ПЕРВЫМ СОБЫТИЕМ ПОТОКА, а не HTTP-статусом (`backend/main.py:1085-1108`).
 * Причина на бэкенде: EventSource не даёт JS ни кода ответа, ни тела —
 * браузер сообщает только «ошибка», — поэтому прежний 403 до открытия
 * StreamingResponse означал, что текст «Вы использовали бесплатную
 * интерпретацию…» до человека не доезжал вовсе: он видел «Соединение
 * прервалось» после трёх реконнектов.
 *
 * Отсюда требование, которое легко нарушить одной строкой `catch (e) =>
 * setError('Не удалось загрузить')`: исходы обязаны РАЗЛИЧАТЬСЯ на экране.
 * «Соединение прервалось» вместо «Оформите Вегу» — это потерянная продажа и
 * злой человек, а не мелкая неточность формулировки.
 */

/**
 * Единственная строка, которую придумывает сам транспорт `_connectSSE`
 * (`api/client.js`) при обрыве. Всё остальное приезжает полем `error` внутри
 * потока и уже является объяснением на русском.
 *
 * ⚠️ Сравнение точное, а не по подстроке: это опознавательный знак нашего
 * же транспорта, а не текст для человека. Совпадение с ним какого-нибудь
 * серверного сообщения означало бы, что серверный текст подменят своим.
 */
export const TRANSPORT_LOST = 'Connection lost';

/** Что показать, когда порвалась связь. Единственный текст, который экран
 *  сочиняет сам, — потому что сервер в этом случае не сказал ничего. */
export const BROKEN_TEXT = 'Соединение прервалось. Проверьте связь и попробуйте снова.';

/** Исходы потока. `refused` — отказ по существу (лимит, тариф), `broken` —
 *  транспорт, `anon` — отказ аутентификации, `done` — успех. */
export const OUTCOMES = Object.freeze({
  DONE: 'done',
  REFUSED: 'refused',
  BROKEN: 'broken',
  ANON: 'anon',
});

/**
 * Классифицирует конец потока.
 *
 * @param {{ error?: unknown, status?: number }} signal
 *        `error` — то, что отдал транспорт (строка `TRANSPORT_LOST` при
 *        обрыве, иначе текст сервера); `status` — HTTP-код, если он вообще
 *        был известен (аноним получает настоящий 403 ДО открытия потока,
 *        `main.py`, ветка `user is None`).
 * @returns {{ outcome: string, text: string, showPricing: boolean, canRetry: boolean }}
 *
 * ⚠️ Отказ по лимиту free и отказ по лимиту lite/pro — ОДИН исход, а не два.
 * Различаются они только текстом, который целиком приходит с сервера (в нём
 * уже стоят и число, и название тарифа). Разводить их здесь значило бы
 * завести в клиенте знание о том, какой тариф что получает, — вторая копия
 * тарифной сетки в этом проекте расходилась не раз.
 */
export function classifyOutcome(signal) {
  const raw = signal?.error;
  const text = typeof raw === 'string' ? raw : '';

  // ⚠️ Проверка анонима стоит ПЕРВОЙ, до ветки успеха. 403 приезжает без
  // текста (отказ аутентификации до открытия потока), и при обратном порядке
  // «нет текста» читалось бы как «поток дошёл до конца»: экран показал бы
  // пустой успешный разбор вместо предложения войти. Поймано тестом.
  if (signal?.status === 403 && !text) {
    // В приложении недостижимо (без сессии экранов нет), ветка держится ради
    // полноты: без неё пустой отказ провалился бы в успех или в refused с
    // пустой строкой.
    return {
      outcome: OUTCOMES.ANON,
      text: 'Войдите в аккаунт, чтобы получить разбор.',
      showPricing: false,
      canRetry: false,
    };
  }

  if (!raw) {
    return { outcome: OUTCOMES.DONE, text: '', showPricing: false, canRetry: false };
  }

  if (text === TRANSPORT_LOST) {
    // Свой текст — сервер ничего не сказал. Кнопки тарифов здесь нет: у
    // человека проблема со связью, а не с подпиской, и предлагать ему
    // купить тариф в этот момент — оскорбительно и бесполезно.
    return { outcome: OUTCOMES.BROKEN, text: BROKEN_TEXT, showPricing: false, canRetry: true };
  }

  // Отказ по существу. Текст сервера — ДОСЛОВНО: он законченное объяснение
  // с числом и названием тарифа, и приставка вроде «Не удалось загрузить
  // разбор:» превратила бы его в сообщение о поломке.
  return { outcome: OUTCOMES.REFUSED, text, showPricing: true, canRetry: false };
}

/**
 * Надо ли перезапросить разбор при возврате приложения из фона
 * (SPEC_INTERPRETATION.md §7).
 *
 * Перезапрос, а не реконнект по таймеру, — потому что `setTimeout` в фоне не
 * выполняется (находка 08.09.2026: таймер обновления сессии на 13-й минуте
 * не выстрелил за 23 минуты), а докачки у ручки нет вовсе: после обрыва
 * поток начинается сначала.
 *
 * Он безопасен по двум свойствам бэкенда, и без них это правило было бы
 * неверным:
 *   · готовый разбор отдаётся БЕЗ проверки лимита (`main.py:1119-1125`) —
 *     если сервер успел досчитать, повтор вернёт текст за ~1 с и ничего не
 *     будет стоить;
 *   · расход списывается только после полного текста
 *     (`main.py:1170-1172`) — если не успел, ничего не потрачено.
 *
 * @param {{ visible: boolean, open: boolean, started: boolean, finished: boolean }} state
 */
export function shouldRefetchOnResume(state) {
  if (!state?.visible) return false;   // ушли в фон, а не вернулись
  if (!state.open) return false;       // экран разбора закрыт — незачем
  if (!state.started) return false;    // ещё не запускали: автозапуска нет
  // ⚠️ Завершённый поток не перезапрашиваем НИКОГДА. После отказа по лимиту
  // повтор дал бы тот же отказ — и экран моргал бы на каждом возврате из
  // фона. После успеха текст уже на экране.
  return !state.finished;
}
