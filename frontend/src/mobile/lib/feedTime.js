/** «2026-08-05T13:35:00+03:00» → «2026-08-05». Срез, не разбор. */
export function datePart(at) {
  return typeof at === 'string' ? at.slice(0, 10) : '';
}

/** «2026-08-05T13:35:00+03:00» → «13:35». Срез, не разбор. */
export function timePart(at) {
  return typeof at === 'string' ? at.slice(11, 16) : '';
}

/**
 * «2026-08-05T13:35:00+03:00» → «05.08». Колонка времени периода на линии
 * (§3 SPEC_FEED_VISUAL.md) — числом, а не словом месяца: там 64 px и
 * «5 августа» в них не влезает.
 */
export function dateShort(at) {
  if (typeof at !== 'string') return '';
  return `${at.slice(8, 10)}.${at.slice(5, 7)}`;
}

/** «30.08 — 19.09» — шапка карточки периода (§5 SPEC_FEED_VISUAL.md). */
export function dateRangeShort(fromAt, toAt) {
  return `${dateShort(fromAt)} — ${dateShort(toAt)}`;
}

/**
 * Разница в календарных днях между двумя «YYYY-MM-DD» (b − a). Через
 * Date.UTC, как shiftDays выше, — переход на летнее время в поясе
 * устройства не должен исказить разницу на сутки.
 */
export function daysBetween(a, b) {
  const [ay, am, ad] = a.split('-').map(Number);
  const [by, bm, bd] = b.split('-').map(Number);
  const diffMs = Date.UTC(by, bm - 1, bd) - Date.UTC(ay, am - 1, ad);
  return Math.round(diffMs / 86400000);
}

/**
 * Календарная дата устройства как «YYYY-MM-DD».
 *
 * Именно локальная дата пользователя, не UTC — решение владельца
 * 05.09.2026: окно ленты отсчитывается от того «сегодня», которое человек
 * видит на своём телефоне. В ночь смены суток UTC-дата отличалась бы на
 * день, и лента открывалась бы не на том дне.
 */
export function localToday() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

/**
 * Календарная дата ± N суток, «YYYY-MM-DD» → «YYYY-MM-DD».
 *
 * Через Date.UTC: перенос через границы месяца и года делает сам календарь,
 * а UTC гарантирует, что переход на летнее время где-нибудь в поясе
 * устройства не отнимет и не прибавит сутки.
 */
export function shiftDays(dateStr, days) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const shifted = new Date(Date.UTC(y, m - 1, d + days));
  const pad = (n) => String(n).padStart(2, '0');
  return `${shifted.getUTCFullYear()}-${pad(shifted.getUTCMonth() + 1)}-${pad(shifted.getUTCDate())}`;
}

/**
 * Заголовок дня: «5 сентября, суббота», для сегодняшнего — «Сегодня,
 * 5 сентября» (§6).
 */
export function dayLabel(dateStr, todayStr) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const month = MONTHS_GENITIVE[m - 1] || '';
  if (dateStr === todayStr) return `Сегодня, ${d} ${month}`;
  const weekday = WEEKDAYS[new Date(Date.UTC(y, m - 1, d)).getUTCDay()];
  return `${d} ${month}, ${weekday}`;
}

/**
 * Заголовок карточки.
 *
 * У транзитов, фаз, затмений, станций и равноденствий заголовок приходит
 * готовым в `text`. У периодов планера (`planner_period`,
 * `planner_moon_house`) `text` пустой — там подпись собирается на клиенте
 * из meta: «Солнце в 11 доме» (решение владельца 05.09.2026, бэкенд не
 * трогаем). Без этого 21 карточка из 718 рисовалась прочерком.
 */
export function eventTitle(event) {
  if (event.text) return event.text;
  const meta = event.meta || {};
  if (meta.planet_name && meta.house) return `${meta.planet_name} в ${meta.house} доме`;
  return '—';
}

/** «2026-08-05» → «ср» — колонка полоски дней (§7). */
export function weekdayShort(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number);
  return WEEKDAYS_SHORT[new Date(Date.UTC(y, m - 1, d)).getUTCDay()];
}

/** «2026-03-31» → «31 марта». Для края горизонта (§9). */
export function dayMonth(dateStr) {
  const [, m, d] = dateStr.split('-').map(Number);
  return `${d} ${MONTHS_GENITIVE[m - 1] || ''}`;
}

// Именительный — он же винительный для месяцев: «по март 2032» (§4).
const MONTHS_NOMINATIVE = [
  'январь', 'февраль', 'март', 'апрель', 'май', 'июнь',
  'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь',
];

/**
 * Срок долгосрочного периода словами: «с ноября 2012 по март 2032» (§4).
 *
 * Два разных падежа в одной фразе, и оба обязательны: предлог «с» требует
 * родительного («с ноября»), предлог «по» — винительного, который у месяцев
 * совпадает с именительным («по март»). Одной формой на оба конца выходило
 * «с ноябре 2012 по марте 2032» — так и было до правки.
 */
export function periodRange(fromAt, toAt) {
  const [fy, fm] = datePart(fromAt).split('-').map(Number);
  const [ty, tm] = datePart(toAt).split('-').map(Number);
  const from = `${MONTHS_GENITIVE[fm - 1] || ''} ${fy}`;
  const to = `${MONTHS_NOMINATIVE[tm - 1] || ''} ${ty}`;
  return `с ${from} по ${to}`;
}

/**
 * Группировка событий по календарному дню их `at` (§5).
 *
 * Порядок событий приходит с бэкенда готовым (max(at, from_date), затем at,
 * затем key) и НЕ пересортировывается — поэтому достаточно одного прохода:
 * события одного дня уже лежат подряд. Дни без событий не появляются вовсе
 * (§6: пустых заголовков нет) — именно потому, что список строится из
 * событий, а не из диапазона дат.
 */
export function groupByDay(events) {
  const days = [];
  let current = null;
  for (const event of events) {
    const date = datePart(event.at);
    if (!current || current.date !== date) {
      current = { date, events: [] };
      days.push(current);
    }
    current.events.push(event);
  }
  return days;
}
